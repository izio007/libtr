# =========================================================================
# 1. ОТКЛЮЧЕНИЕ ДРАЙВЕРА NOUVEAU ДЛЯ ОЖИВЛЕНИЯ NVIDIA
# =========================================================================
# Добавляем Nouveau в черный список ядра Linux
sudo tee /etc/modprobe.d/blacklist-nouveau.conf <<EOF
blacklist nouveau
options nouveau modeset=0
EOF

# Обновляем конфигурацию загрузчика, чтобы ядро забыло про Nouveau
sudo update-initramfs -u

# =========================================================================
# 2. ОЧИСТКА СЛОМАННЫХ РЕПОЗИТОРИЕВ И ИСПРАВЛЕНИЕ АРТ
# =========================================================================
# Удаляем некорректный файл, вызвавший ошибку синтаксиса APT
sudo rm -f /etc/apt/sources.list.d/nvidia-container-toolkit.list
sudo apt update

# =========================================================================
# 3. ЧИСТАЯ УСТАНОВКА PYTEST (В ОБХОД ЗАЩИТЫ PYTHON)
# =========================================================================
# Используем флаг --break-system-packages, чтобы разрешить установку на сервере разработчика
sudo pip3 install pytest --break-system-packages

# =========================================================================
# 4. ПРАВИЛЬНЫЙ ЗАПУСК ИНСТАЛЛЯТОРОВ С ФЛЕШКИ
# =========================================================================
# Переходим строго в физическую папку, где лежат все ваши файлы
cd /mnt/usb/ollama/

# Запускаем установку драйвера NVIDIA заново (теперь Nouveau не помешает после перезагрузки)
sudo ./nvidia-driver-550.run --silent --dkms
sudo ./cuda-toolkit-12.4.1.run --silent --toolkit

# Распаковываем бинарный файл Ollama
sudo tar -C /usr -xzf ollama-linux-amd64.tar.zst
sudo systemctl daemon-reload
sudo systemctl restart ollama

# Устанавливаем локальный GitLab сервер напрямую из текущей рабочей директории флешки
sudo dpkg -i gitlab-ce_16.1.1-ce.0_amd64.deb
sudo dpkg -i gitlab-runner_amd64.deb

# Запускаем финальную конфигурацию GitLab
sudo gitlab-ctl reconfigure
