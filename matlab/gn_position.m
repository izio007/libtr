function [status, lambda] = gn_position(P, alpha, beta, var_alpha, var_beta)
% =========================================================================
% CORE MATH KERNEL: NONLINEAR GAUSS-NEWTON POSITION ESTIMATION (GN)
% SYSTEM MATRIX CONTEXT: DE CARTESIAN METRIC CANON (ECHELON A)
%
% PURPOSE:
%   Итерационный нелинейный метод Гаусса-Ньютона в декартовом прямоугольном 
%   пространстве локальной земли ENU. Выполняет поиск оценки вектора состояния 
%   строго в абсолютных метрах и радианах СИ без применения масштабирующих щитов.
%   Предназначен для фиксации затухания градиентного спуска в овражном рельефе.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат базовых постов ТИС, размер [3 x M], метры.
%               Строки соответствуют осям [x_si; y_si; z_si] в локальной СК ENU.
%   alpha     - Вектор зашумленных азимутов цели, размер [M x 1], радианы.
%               Отсчет ведется от положительного направления оси OX против часовой стрелки.
%   beta      - Вектор зашумленных углов места цели, размер [M x 1], радианы.
%               Отсчет ведется от горизонтальной плоскости XOY вверх в диапазоне [-pi/2; pi/2].
%   var_alpha - Вектор дисперсий шума каналов азимута постов, размер [M x 1], рад^2.
%               (В Эшелоне А GN зарезервирован для интерфейсной сквозной совместимости).
%   var_beta  - Вектор дисперсий шума каналов угла места постов, размер [M x 1], рад^2.
%               (В Эшелоне А GN зарезервирован для интерфейсной сквозной совместимости).
%
% OUTPUT ARGUMENTS:
%   status    - Код завершения вычислительной операции (Выходной аналитический признак):
%               0: Успешный расчет, ранг измерительной матрицы удержан, сходимость достигнута.
%               1: Недостаточно информации для МНК (число активных постов измерительной сети M < 2).
%               2: Геометрическое вырождение, критическое падение ранга матрицы нормальных
%                  уравнений (rcond < eps), либо расходимость процесса за max_iter шагов.
%   lambda    - Рассчитанный декартов вектор координат объекта [X; Y; Z], метры.
%               При status != 0 возвращает строго [NaN; NaN; NaN].
%
% COMPILER ARCHITECTURE REQUIREMENT (ANSI C99 COMPLIANCE):
%   - Исключить динамическое выделение памяти в процессе вычислений.
%   - Начальное приближение итератора извлекается из равноточного ядра lls_position.
%   - Все тригонометрические инварианты линеаризуются строго от инвариантной оси OX.
%   - Проверка обусловленности выполняется по машинному нулю без регуляризаций.
% =========================================================================

lambda = [NaN; NaN; NaN];
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

% 2. ДИНАМИЧЕСКАЯ ИНИЦИАЛИЗАЦИЯ ИЗ ВНУТРЕННЕЙ СТАРТОВОЙ ЛИНЕЙНОЙ ЗАСЕЧКИ
[st_lls, lambda_lls] = lls_position(P, alpha, beta);
if st_lls ~= 0
    status = st_lls; return;
end

x = lambda_lls(1);
y = lambda_lls(2);
z = lambda_lls(3);

max_iter = 100;
epsilon_angle = 1e-5; % Уставной допуск на останов по стабильности углового функционала
converged = false;

% 3. ИТЕРАЦИОННЫЙ ПРОЦЕСС ОПТИМИЗАЦИИ В СТЕРИЛЬНОМ ДЕКАРТОВОМ ПРОСТРАНСТВЕ
for iter = 1:max_iter
    
    J_cart = zeros(2 * M, 3);
    residual = zeros(2 * M, 1);
    
    % Синхронизация линеаризации: расчет приращений по актуальной точке спуска
    for i = 1:M
        xs = P(1, i); ys = P(2, i); zs = P(3, i);
        
        % Вектор пространственной дальности в абсолютных метрах земли
        dx_i = x - xs;
        dy_i = y - ys;
        dz_i = z - zs;
        
        r_xy_i_sq = dx_i^2 + dy_i^2;
        r_xy_i = sqrt(r_xy_i_sq);
        if r_xy_i < 1e-3, r_xy_i = 1e-3; r_xy_i_sq = 1e-6; end
        
        r_i_sq = r_xy_i_sq + dz_i^2;
        r_i = sqrt(r_i_sq);
        if r_i < 1e-3, r_i = 1e-3; r_i_sq = 1e-6; end
        
        % Прогнозный измерительный пучок пеленгации i-го поста
        alpha_pred = atan2(dy_i, dx_i);
        beta_pred  = atan2(dz_i, r_xy_i);
        
        % Вычисление невязок с приведением фазы к главному тригонометрическому интервалу
        ang_res_a = alpha(i) - alpha_pred;
        ang_res_a = atan2(sin(ang_res_a), cos(ang_res_a));
        
        ang_res_b = beta(i) - beta_pred;
        ang_res_b = atan2(sin(ang_res_b), cos(ang_res_b));
        
        residual(2*i-1, 1) = ang_res_a;
        residual(2*i,   1) = ang_res_b;
        
        % Сборка строк декартовой матрицы Якоби J_cart (Строгий вывод из Раздела 2)
        % 2.1. Строка горизонтального канала (Азимут)
        J_cart(2*i-1, 1) = -dy_i / r_xy_i_sq;
        J_cart(2*i-1, 2) =  dx_i / r_xy_i_sq;
        J_cart(2*i-1, 3) =  0;
        
        % 2.2. Строка вертикального канала (Угол места)
        J_cart(2*i, 1)   = -(dx_i * dz_i) / (r_i_sq * r_xy_i);
        J_cart(2*i, 2)   = -(dy_i * dz_i) / (r_i_sq * r_xy_i);
        J_cart(2*i, 3)   =  r_xy_i / r_i_sq;
    end
    
    % Линеаризованная матрица нормальных уравнений Гаусса-Ньютона без весов W
    AtA = J_cart.' * J_cart;
    
    % Проверка числового вырождения строго по машинному нулю вещественной сетки
    if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
        status = 2; return; % Честный аналитический отмах при потере ранга в овраге
    end
    
    % Вычисление декартова вектора шага поправок
    delta_X = AtA \ (J_cart.' * residual);
    
    % Проверка канонического критерия останова ТИС по стабильности угловых невязок
    if max(abs(J_cart * delta_X)) < epsilon_angle
        converged = true;
    end
    
    % Обновление оцениваемого декартова вектора состояния
    x = x + delta_X(1);
    y = y + delta_X(2);
    z = z + delta_X(3);
    
    if converged
        break;
    end
end

if ~converged
    status = 2; return;
end

lambda = [x; y; z];
status = 0;
end
