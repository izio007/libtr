function [status, W_diag] = lls3d_prepare_data(P, alpha, beta, var_alpha, var_beta)
% =========================================================================
% ФУНКЦИЯ НЕПРЕРЫВНОГО ГАУССОВА ДЕМПФИРОВАНИЯ ИНФОРМАЦИОННЫХ ВЕСОВ
% =========================================================================
% Входные параметры:
%   P         - Матрица координат измерительных пунктов [3 x M]
%   alpha     - Вектор сырых измеренных азимутов цели [M x 1] (радианы)
%   beta      - Вектор сырых измеренных углов места цели [M x 1] (радианы)
%   var_alpha - Вектор дисперсий шума азимутальных каналов [M x 1]
%   var_beta  - Вектор дисперсий шума угломестных каналов [M x 1]
% Выходные параметры:
%   status    - Флаг выполнения (0 - успешно, 1 - ошибка размерностей)
%   W_diag    - Непрерывный вектор весов для 2M уравнений связи [2M x 1]
% =========================================================================

MAX_STATIONS = 128;
M = size(P, 2);
W_diag = ones(2*M, 1);

if M < 2 || M > MAX_STATIONS || length(alpha) < M || length(beta) < M
    status = 1; return;
end

% Параметр гладкости защитного углового сектора (4 градуса в радианах)
sigma_0 = deg2rad(4.0); 

% Непрерывный анализ плотности пучка по сырым входным азимутам alpha
for i = 1:M
    density_sum = 0.0;
    for j = 1:M
        % Кратчайшая угловая разность между пеленгами i и j
        diff_a = abs(alpha(i) - alpha(j));
        if diff_a > pi, diff_a = 2*pi - diff_a; end
        
        % Накопление гладкого вклада плотности по экспоненте
        density_sum = density_sum + exp(-(diff_a^2) / (2 * sigma_0^2));
    end
    
    % Математическая защита: плотность одиночного изолированного луча равна 1.0
    if density_sum < 1.0, density_sum = 1.0; end
    
    % Назначение непрерывных весов (обратно пропорционально плотности пучка)
    W_diag(2*i-1) = 1.0 / density_sum; % Вес азимутального уравнения
    W_diag(2*i)   = 1.0 / density_sum; % Вес угломестного уравнения
end

status = 0;
end
