function [status, lambda] = mock_position(P, alpha, beta, var_alpha, var_beta)
% =========================================================================
% TIS IMITATION KERNEL: IDEAL CARTESIAN POSITIONER OPERATOR (MOCK)
% SYSTEM MATRIX CONTEXT: METRIC SI-CANON (ECHELON A - PURE GEOMETRIC PHYSICS)
%
% PURPOSE:
%   Расчет физически истинных пространственных координат объекта на основе 
%   идеальных, незашумленных угловых измерений. Обеспечивает сквозную 
%   конвейерную взаимозаменяемость с прикладными алгоритмами оценивания 
%   измерительного контура ТИС.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат измерительных постов ТИС, размер [3 x M], метры.
%               Строки соответствуют декартовым осям [x_si; y_si; z_si] в локальной СК ENU.
%   alpha     - Вектор идеальных азимутов цели, размер [M x 1], радианы.
%               Отсчет строго от положительного направления оси OX против часовой.
%   beta      - Вектор идеальных углов места цели, размер [M x 1], радианы.
%               Отсчет строго от плоскости XOY вверх в диапазоне [-pi/2; pi/2].
%   var_alpha - Вектор дисперсий шума азимута постов, размер [M x 1], рад^2.
%               (В имитационном ядре зарезервирован для сквозной совместимости интерфейсов).
%   var_beta  - Вектор дисперсий шума угла места постов, размер [M x 1], рад^2.
%               (В имитационном ядре зарезервирован для сквозной совместимости интерфейсов).
%
% OUTPUT ARGUMENTS:
%   status    - Код завершения операции (Выходной аналитический признак):
%               0: Успешный расчет, ранг измерительной матрицы ТИС удержан.
%               1: Недостаточно информации для МНК (число активных постов M < 2).
%               2: Геометрическое вырождение, критическое падение ранга матрицы нормальных уравнений.
%   lambda    - Рассчитанный декартов вектор истинных координат [X; Y; Z], метры.
%               При status != 0 возвращает строго [NaN; NaN; NaN].
%
% COMPILER ARCHITECTURE REQUIREMENT (ANSI C99 COMPLIANCE):
%   - Исключить динамическое выделение памяти в процессе вычислений.
%   - Исключить разложение Холецкого и искусственное наложение стохастического шума.
%   - Все тригонометрические инварианты линеаризуются строго от инвариантной оси OX.
%   - Проверка обусловленности выполняется по машинному нулю без регуляризаций.
% =========================================================================

lambda = [NaN; NaN; NaN];
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

H_init = zeros(2 * M, 3);
b_init = zeros(2 * M, 1);

% 2. СБОРКА СТРОК ИЗМЕРИТЕЛЬНОЙ МАТРИЦЫ И ВЕКТОРА СВОБОДНЫХ ЧЛЕНОВ (БАЗИС OX)
for i = 1:M
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    
    % Строка горизонтального канала визирования (Азимут)
    H_init(2*i-1, 1) = sa;
    H_init(2*i-1, 2) = -ca;
    H_init(2*i-1, 3) = 0;
    b_init(2*i-1, 1) = sa * xs - ca * ys;
    
    % Строка вертикального канала визирования (Угол места) - Правая декартова СК ENU
    H_init(2*i, 1) = -ca * sb;
    H_init(2*i, 2) = -sa * sb;
    H_init(2*i, 3) = cb;
    b_init(2*i, 1) = -ca * sb * xs - sa * sb * ys + cb * zs;
end

AtA_init = H_init.' * H_init;

% 3. АБСОЛЮТНАЯ АНАЛИТИЧЕСКАЯ ЧЕСТНОСТЬ ПО МАШИННОМУ НУЛЮ ВЕЩЕСТВЕННОЙ СЕТКИ
if rcond(AtA_init) < 2.2204e-16 || isnan(rcond(AtA_init))
    status = 2; return;
end

% 4. БЕЗИТЕРАЦИОННОЕ НАХОЖДЕНИЕ ЦЕНТРА ПЕРЕСЕЧЕНИЯ ИДЕАЛЬНЫХ ЛУЧЕЙ В РАМКАХ ЕДИНОГО МАТЕМАТИЧЕСКОГО ОПЕРАТОРА
lambda = AtA_init \ (H_init.' * b_init);
status = 0;
end
