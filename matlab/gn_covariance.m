function [status, K_cart] = gn_covariance(P, alpha, beta, var_alpha, var_beta, lambda)
% =========================================================================
% CORE MATH KERNEL: DE CARTESIAN COVARIANCE FOR GAUSS-NEWTON METHOD (GN)
% SYSTEM MATRIX CONTEXT: EXACT FISHER INFORMATION MATRIX WITH WEIGHTS W
%
% PURPOSE:
%   Расчет полной декартовой ковариационной матрицы погрешностей оценивания GN
%   размерности [3 x 3] под текущую пачку измерительных данных в абсолютных 
%   метрах земли ENU. Вычисляется на основе обращения взвешенной информационной 
%   матрицы Фишера в финальной точке схождения градиентного спуска.
%   Сохраняет все взаимные корреляционные моменты и пространственные скосы осей.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат измерительных постов ТИС, размер [3 x M], метры.
%               Строки соответствуют декартовым осям [x_si; y_si; z_si] in локальной СК ENU.
%   alpha     - Вектор зашумленных азимутов цели, размер [M x 1], радианы.
%               Отсчет ведется от положительного направления оси OX против часовой стрелки.
%   beta      - Вектор зашумленных углов места цели, размер [M x 1], радианы.
%               Отсчет ведется от горизонтальной плоскости XOY вверх в диапазоне [-pi/2; pi/2].
%   var_alpha - Паспортный вектор дисперсий шума каналов азимута постов, размер [M x 1], рад^2.
%   var_beta  - Паспортный вектор дисперсий шума каналов угла места постов, размер [M x 1], рад^2.
%   lambda    - Рассчитанный декартов вектор координат цели [X; Y; Z], полученный 
%               из математического оператора gn_position при успешной сходимости, метры.
%
% OUTPUT ARGUMENTS:
%   status    - Код завершения вычислительной операции (Выходной аналитический признак):
%               0: Успешный расчет ковариации, информационная матрица Фишера обратима.
%               1: Недостаточно информации для МНК (число активных постов измерительной сети M < 2).
%               2: Геометрическое вырождение, критическое падение ранга матрицы нормальных
%                  уравнений (rcond < eps). Матрица K_cart возвращается как [3 x 3] из NaN.
%   K_cart    - Полная инвариантная декартова ковариационная матрица погрешностей ТИС,
%               размер [3 x 3], ед. изм.: метры^2. Содержит все перекрестные корреляционные
%               моменты и пространственные скосы осей эллипсоида рассеяния.
%
% COMPILER ARCHITECTURE REQUIREMENT (ANSI C99 COMPLIANCE):
%   - Исключить динамическое выделение памяти в процессе вычислений.
%   - Все частные производные линеаризуются строго от инвариантной оси OX.
%   - Проверка обусловленности выполняется по машинному нулю без регуляризаций.
% =========================================================================

K_cart = NaN(3, 3);
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

J_cart = zeros(2 * M, 3);
W = zeros(2 * M, 2 * M);

x = lambda(1); y = lambda(2); z = lambda(3);

% 2. СБОРКА АНАЛИТИЧЕСКОЙ ДЕКАРТОВОЙ МАТРИЦЫ ЯКОБИ И БЕЗРАЗМЕРНЫХ ВЕСОВ ГАУССА-МАРКОВА
for i = 1:M
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    
    % Вектор пространственной дальности в абсолютных метрах земли
    dx_i = x - xs;
    dy_i = y - ys;
    dz_i = z - zs;
    
    r_xy_i_sq = dx_i^2 + dy_i^2;
    r_xy_i = sqrt(r_xy_i_sq);
    if r_xy_i < 1e-3, r_xy_i = 1e-3; r_xy_i_sq = 1e-6; end
    
    r_i_sq = r_xy_i_sq + dz_i^2;
    r_i = sqrt(r_i_sq);
    if r_i < 1e-3, r_i = 1e-3; r_i_sq = 1e-6; end
    
    % Формирование безразмерной весовой матрицы из углового измерительного пространства [1/рад^2]
    W(2*i-1, 2*i-1) = 1.0 / var_alpha(i);
    W(2*i,   2*i)   = 1.0 / var_beta(i);
    
    % Расчет частных производных декартова канонического Якобиана J_cart (Раздел 2 паспорта)
    % 2.1. Строка горизонтального канала (Азимут)
    J_cart(2*i-1, 1) = -dy_i / r_xy_i_sq;
    J_cart(2*i-1, 2) =  dx_i / r_xy_i_sq;
    J_cart(2*i-1, 3) =  0;
    
    % 2.2. Строка вертикального канала (Угол места)
    J_cart(2*i, 1)   = -(dx_i * dz_i) / (r_i_sq * r_xy_i);
    J_cart(2*i, 2)   = -(dy_i * dz_i) / (r_i_sq * r_xy_i);
    J_cart(2*i, 3)   =  r_xy_i / r_i_sq;
end

% Формирование взвешенной декартовой матрицы нормальных уравнений (Информационной матрицы Фишера)
AtA = J_cart.' * W * J_cart;

% 3. ОЦЕНКА ЧИСЛЕННОГО ВЫРОЖДЕНИЯ СТРОГО ПО МАШИННОМУ НУЛЮ ВЕЩЕСТВЕННОЙ СЕТКИ
if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
    status = 2; return; % Бескомпромиссный отмах при потере ранга жесткости на дне оврага
end

% 4. ВЫЧИСЛЕНИЕ ДЕКАРТОВА ТЕНЗОРА ОШИБОК ПРЯМЫМ ИНВЕРТИРОВАНИЕМ (СЛОЙ А, РАЗДЕЛ 4)
K_cart = inv(AtA);
status = 0;
end
