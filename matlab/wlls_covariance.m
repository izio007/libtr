function [status, std_X, std_Y, std_Z] = wlls_covariance(P, alpha, beta, var_alpha, var_beta, lambda)
% =========================================================================
% CORE MATH KERNEL: DE CARTESIAN COVARIANCE FOR WEIGHTED LEAST SQUARES (WLLS)
% SYSTEM MATRIX CONTEXT: INVERSE NORMAL EQUATIONS OPERATOR (K = inv(H.' * H))
%
% PURPOSE: 
%   Расчет декартовой ковариационной матрицы погрешностей WLLS (параметров 
%   и угла поворота эллипса рассеяния по уровню 1 сигма) на основе геометрии 
%   взвешенных измерительных строк ТИС.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат постов ТИС, размер [3 x M], метры.
%   alpha     - Вектор азимутов цели, размер [M x 1], радианы (от оси OX).
%   beta      - Вектор углов места цели, размер [M x 1], радианы (от плоскости XOY).
%   var_alpha - Вектор дисперсий шума азимута датчиков, размер [M x 1], рад^2.
%   var_beta  - Вектор дисперсий шума угла места датчиков, размер [M x 1], рад^2.
%   lambda    - УЖЕ РАССЧИТАННЫЙ на текущем такте декартов вектор координат 
%               цели [X; Y; Z] из ОЗУ (исключает повторный вызов МНК), метры.
%
% OUTPUT ARGUMENTS:
%   status - Код завершения операции (Выходной регистр Си-модуля):
%            0: Успешный расчет ковариационной матрицы WLLS.
%            1: Недостаточно информации для МНК (M < 2).
%            2: Геометрическое вырождение, детерминант ушел в машинный ноль.
%   std_X  - Среднеквадратическое отклонение (СКО) по оси OX, метры.
%   std_Y  - Среднеквадратическое отклонение (СКО) по оси OY, метры.
%   std_Z  - Среднеквадратическое отклонение (СКО) по оси OZ, метры.
% =========================================================================

std_X = NaN; std_Y = NaN; std_Z = NaN;
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

H = zeros(2*M, 3);
x = lambda(1); y = lambda(2); z = lambda(3);

% 2. СБОРКА ИЗМЕРИТЕЛЬНОЙ МАТРИЦЫ H С УЧЕТОМ РАЗМЕРНЫХ ВЕСОВ ГАУССА-МАРКОВА
for i = 1:M
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    
    % Вычисление квадрата расстояния до i-го поста ТИС
    rho_sq = (x - xs)^2 + (y - ys)^2 + (z - zs)^2;
    if rho_sq < 1e-3, rho_sq = 1e-3; end
    
    % Расчет размерных весов линеаризации [1 / метры]
    w_a = 1.0 / sqrt(var_alpha(i) * rho_sq);
    w_b = 1.0 / sqrt(var_beta(i) * rho_sq);
    
    % Взвешенная строка азимута ТИС (от оси OX)
    H(2*i-1, 1) = w_a * sa;
    H(2*i-1, 2) = w_a * (-ca);
    H(2*i-1, 3) = 0;
    
    % Взвешенная строка угла места ТИС (ИСТИННЫЙ ВЕРИФИЦИРОВАННЫЙ ЗНАК ТИС)
    H(2*i, 1) = w_b * (-ca * sb);
    H(2*i, 2) = w_b * (-sa * sb);
    H(2*i, 3) = w_b * cb;
end

AtA = H.' * H;

% 3. ЧЕСТНЫЙ АНАЛИТИЧЕСКИЙ ОТКАЗ ПО МАШИННОМУ НУЛЮ РЕЗОЛЬВЕНТЫ
if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
    status = 2; return;
end

% 4. ПЕРЕНОС ОШИБОК ДЛЯ WLLS: КОВАРИАЦИЯ ЕСТЬ ОБРАТНАЯ МАТРИЦА ФИШЕРА
K_wlls = inv(AtA);

% 5. ИЗВЛЕЧЕНИЕ ПАРАМЕТРОВ ОПИСАННОГО ДЕКАРТОВА БОКСА ВОКРУГ ЭЛЛИПСОИДА РАССЕЯНИЯ
std_X = sqrt(K_wlls(1, 1));
std_Y = sqrt(K_wlls(2, 2));
std_Z = sqrt(K_wlls(3, 3));
status = 0;
end
