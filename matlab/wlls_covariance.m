function [status, K_cart] = wlls_covariance(P, alpha, beta, var_alpha, var_beta, lambda_est)
% =========================================================================
% CORE MATH KERNEL: DE CARTESIAN COVARIANCE FOR WEIGHTED LEAST SQUARES (WLLS)
% SYSTEM MATRIX CONTEXT: EXACT FISHER INFORMATION MATRIX FROM WEIGHTED SYSTEM
%
% PURPOSE:
%   Расчет полной декартовой ковариационной матрицы погрешностей WLLS
%   размерности [3 x 3] под текущую пачку измерений в абсолютных метрах земли ENU.
%   Вычисляется на основе обращения нормальной матрицы взвешенной системы.
%   Сохраняет все взаимные корреляционные моменты и пространственные скосы осей.
%
% INPUT ARGUMENTS:
%   P          - Матрица координат базовых постов ТИС, размер [3 x M], метры.
%   alpha      - Вектор зашумленных азимутов цели, размер [M x 1], радианы.
%   beta       - Вектор зашумленных углов места цели, размер [M x 1], радианы.
%   var_alpha  - Паспортный вектор дисперсий шума азимута постов, размер [M x 1], рад^2.
%   var_beta   - Паспортный вектор дисперсий шума угла места постов, размер [M x 1], рад^2.
%   lambda_est - Рассчитанный декартов вектор координат [X; Y; Z] из wlls_position, метры.
%
% OUTPUT ARGUMENTS:
%   status     - Код завершения операции (Выходной аналитический признак):
%                0: Успешный расчет ковариации, ранг взвешенной нормальной матрицы удержан.
%                1: Недостаточно информации для МНК (число активных постов M < 2).
%                2: Численное вырождение нормальных уравнений (rcond < eps). Матрица K_cart из NaN.
%   K_cart     - Полная декартова ковариационная матрица погрешностей ТИС, размер [3 x 3],
%                ед. изм.: метры^2. Усечение до диагональных компонент запрещено.
%
% ATTENTION (ЭШЕЛОН Б / ЗОНА КРАХА):
%   Ввиду отсутствия априорного знания об истинных координатах объекта, 
%   линеаризация двухстороннего матричного преобразования Гаусса-Маркова вынужденно 
%   выполняется относительно рантайм-оценки lambda_est из wlls_position. 
%   На дальних рубежах (450 км) котангенсный Bias линейного метода приведет 
%   к искусственному занижению расчетных плеч дальностей rho_sq, что порождает 
%   систематическое занижение компонент матрицы K_cart относительно реального 
%   эмпирического рассеяния точек. Данное расхождение является врожденным 
%   ограничением метода LLS/WLLS и подлежит исследованию.
%
% COMPILER ARCHITECTURE REQUIREMENT (ANSI C99 COMPLIANCE):
%   - Исключить динамическое выделение памяти в процессе вычислений.
%   - Финальный декартов тензор ошибок формируется чистым обращением нормальной матрицы.
%   - Проверка обусловленности выполняется по машинному нулю без регуляризаций.
% =========================================================================

K_cart = NaN(3, 3);
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

H_w = zeros(2 * M, 3);
x = lambda_est(1); y = lambda_est(2); z = lambda_est(3);

% 2. СБОРКА ВЗВЕШЕННОЙ ИЗМЕРИТЕЛЬНОЙ МАТРИЦЫ СВЯЗИ В РАМКАХ ЕДИНОГО КОНТУРА
for i = 1:M
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    
    % Вычисление плеча рычага до i-го поста от рантайм-оценки декартовых координат lambda_est
    rho_sq = (x - xs)^2 + (y - ys)^2 + (z - zs)^2;
    if rho_sq < 1e-3, rho_sq = 1e-3; end
    rho = sqrt(rho_sq);
    
    % Размерные веса Гаусса-Маркова линеаризации взвешенной строки [1 / метр]
    w_a = 1.0 / (sqrt(var_alpha(i)) * rho);
    w_b = 1.0 / (sqrt(var_beta(i)) * rho);
    
    % Наполнение строк взвешенной матрицы системы нормальных уравнений
    H_w(2*i-1, 1) = w_a * sa;
    H_w(2*i-1, 2) = w_a * (-ca);
    H_w(2*i-1, 3) = 0;
    
    H_w(2*i, 1) = w_b * (-ca * sb);
    H_w(2*i, 2) = w_b * (-sa * sb);
    H_w(2*i, 3) = w_b * cb;
end

AtA_w = H_w.' * H_w;

% 3. АБСОЛЮТНАЯ АНАЛИТИЧЕСКАЯ ЧЕСТНОСТЬ ПО МАШИННОМУ НУЛЮ ВЕЩЕСТВЕННОЙ СЕТКИ
if rcond(AtA_w) < 2.2204e-16 || isnan(rcond(AtA_w))
    status = 2; return; % Мгновенный аналитический отмах при потере ранга жесткости
end

% 4. ВЫЧИСЛЕНИЕ РЕЗУЛЬТИРУЮЩЕГО ДЕКАРТОВА ТЕНЗОРА ОШИБОК ПРИОРИТЕТНЫМ ОБРАЩЕНИЕМ
K_cart = inv(AtA_w);
status = 0;
end
