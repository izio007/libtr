function [status, lambda] = lls_position(P, alpha, beta, var_alpha, var_beta)
% =========================================================================
% CORE MATH KERNEL: LINEAR LEAST SQUARES POSITION ESTIMATION (LLS)
% SYSTEM MATRIX CONTEXT: UNWEIGHTED GAUSS-MARKOV MODEL (SI-CANON)
%
% PURPOSE: 
%   Мгновенный расчет пространственных декартовых координат цели в один такт 
%   без итераций и без начального приближения на основе линейного МНК 
%   в прямоугольной локальной СК земли ENU. Оперирует строго в абсолютных 
%   метрах и радианах СИ для фиксации котангенсного Bias-сжатия.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат базовых постов ТИС, размер [3 x M], метры.
%               Строки соответствуют осям [x_si; y_si; z_si] в локальной СК ENU.
%   alpha     - Вектор зашумленных азимутов цели, размер [M x 1], радианы.
%               Отсчет строго от положительного направления оси OX против часовой.
%   beta      - Вектор зашумленных углов места цели, размер [M x 1], радианы.
%               Отсчет строго от плоскости XOY вверх в диапазоне [-pi/2; pi/2].
%   var_alpha - Паспортный вектор дисперсий шума азимута постов, размер [M x 1], рад^2.
%               (В Эшелоне А LLS зарезервирован для сквозной совместимости интерфейсов).
%   var_beta  - Паспортный вектор дисперсий шума угла места постов, размер [M x 1], рад^2.
%               (В Эшелоне А LLS зарезервирован для сквозной совместимости интерфейсов).
%
% OUTPUT ARGUMENTS:
%   status    - Код завершения операции (Выходной регистр Си-модуля):
%               0: Успешный расчет, ранг измерительной матрицы ТИС удержан.
%               1: Недостаточно информации для МНК (число активных постов M < 2).
%               2: Геометрическое вырождение, критическое падение ранга матрицы нормальных уравнений.
%   lambda    - Рассчитанный декартов вектор координат [X; Y; Z], метры.
%               При status != 0 возвращает строго [NaN; NaN; NaN].
%
% COMPILER ARCHITECTURE REQUIREMENT (GCC / ANSI C99):
%   - Категорически исключить динамическую аллокацию ОЗУ (malloc). Matrix buffers строго double.
%   - Все тригонометрические инварианты линеаризуются строго от оси OX против часовой стрелки.
%   - Проверка обусловленности выполняется по машинному нулю без SVD-маскировки и регуляризаций.
% =========================================================================

lambda = [NaN; NaN; NaN];
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

H = zeros(2 * M, 3);
b = zeros(2 * M, 1);

% 2. СБОРКА ИЗМЕРИТЕЛЬНОЙ МАТРИЦЫ И ВЕКТОРА СВОБОДНЫХ ЧЛЕНОВ (БАЗИС OX)
for i = 1:M
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    
    % Аналитический вывод строки горизонтального канала (Азимут alpha_i)
    H(2*i-1, 1) = sa;
    H(2*i-1, 2) = -ca;
    H(2*i-1, 3) = 0;
    b(2*i-1, 1) = sa * xs - ca * ys;
    
    % Аналитический вывод строки вертикального канала (Угол места beta_i)
    H(2*i, 1) = -ca * sb;
    H(2*i, 2) = -sa * sb;
    H(2*i, 3) = cb;
    b(2*i, 1) = -ca * sb * xs - sa * sb * ys + cb * zs;
end

AtA = H.' * H;

% 3. АБСОЛЮТНАЯ АНАЛИТИЧЕСКАЯ ЧЕСТНОСТЬ ПО МАШИННОМУ НУЛЮ ВЕЩЕСТВЕННОЙ СЕТКИ
if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
    status = 2; return; % Честный аналитический отмах при потере ранга
end

% 4. ПРЯМОЙ БЕЗИТЕРАЦИОННЫЙ РАСЧЕТ ДЕКАРТОВЫХ КООРДИНАТ ОБЪЕКТА В ОДИН ТАКТ
lambda = AtA \ (H.' * b);
status = 0;
end
