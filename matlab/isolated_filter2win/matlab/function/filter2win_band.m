function band=filter2win_band(model,c,elapsed)
% Shared robust gate and model-quality calculation, in coordinate units.
% Margins are MINIMUM radii, not additions to k*MAD. No sigma is inferred.
scale=c.mad_floor;
if isfinite(model.mad), scale=max(model.mad,scale); end
adaptive=min(c.max_adaptive_radius,c.mad_multiplier*scale);
growth=c.growth_per_second*max(0,elapsed);
band=struct('lower',max(c.lower_margin,adaptive)+growth, ...
    'upper',max(c.upper_margin,adaptive)+growth, ...
    'exit_lower',max(c.exit_lower_margin,adaptive)+growth, ...
    'exit_upper',max(c.exit_upper_margin,adaptive)+growth, ...
    'adaptive',adaptive,'quality',false);
% Quality refers to the observed detrended window, without age growth.
band.quality=isfinite(model.level) && isfinite(model.velocity) && ...
    isfinite(model.mad) && model.mad<=c.max_mad && ...
    abs(model.velocity)<=c.max_abs_velocity && ...
    isfinite(model.trimmed_range) && model.trimmed_range<=c.max_trimmed_range && ...
    model.trimmed_min_residual>=-max(c.lower_margin,adaptive) && ...
    model.trimmed_max_residual<=max(c.upper_margin,adaptive);
end
