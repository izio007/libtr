%[text] ## 1. ГЕОМЕТРИЧЕСКИЙ БАЗИС И АППАРАТНО-ГЕОМЕТРИЧЕСКИЕ ВЕСА ТИС
%[text] 
%[text] Триангуляционно-Измерительная Система (ТИС) осуществляет пассивную пеленгацию цели с координатами:
%[text] $\\mathbf{X}=\[x,y,z\]^T$
%[text] 
%[text] Сеть состоит из M базовых постов с известными декартовыми координатами:
%[text] $\\mathbf{X}\_{si}=\[x\_{si},y\_{si},z\_{si}\]^T,\\quad i=1,\\dots,M$
%[text] 
%[text] Вектор дальности (прямой визирный луч) из i-го измерительного поста в цель задается приращениями:
%[text] $\\Delta x\_i=x-x\_{si}$
%[text] $\\Delta y\_i=y-y\_{si}$
%[text] $\\Delta z\_i=z-z\_{si}$
%[text] 
%[text] Проекция визирного луча на горизонтальную плоскость XOY (продольная дальность):
%[text] $r\_{xy,i}=\\sqrt{\\Delta x\_i^2+\\Delta y\_i^2}$
%[text] 
%[text] Полная пространственная дальность до цели составляет:
%[text] $\\rho\_i=\\sqrt{\\Delta x\_i^2+\\Delta y\_i^2+\\Delta z\_i^2}$
%[text] 
%[text] В отличие от невесового метода LLS, Взвешенный Линейный МНК (WLLS) минимизирует квадратичную форму остатков, учитывая как аппаратную неравноточность измерительных каналов, так и геометрическое удаление цели от постов ТИС.
%[text] 
%[text] Чтобы минимизируемый функционал МНК $J=\\mathbf{e}^T\\cdot W\\cdot\\mathbf{e}$ являлся безразмерной величиной, элементы матрицы весов W обязаны обладать физической размерностью $[1/\\text{метры}^2]$. Линейная дисперсия шума на местности прямо пропорциональна квадрату плеча рычага — дальности $\\rho\_i^2$. Истинная размерная матрица весов W Гаусса-Маркова имеет строго диагональную структуру:
%[text] $W=\\text{diag}(\\frac{1}{\\sigma\_{\\alpha 1}^2\\cdot\\rho\_1^2},\\quad\\frac{1}{\\sigma\_{\\beta 1}^2\\cdot\\rho\_1^2},\\quad\\dots,\\quad\\frac{1}{\\sigma\_{\\alpha M}^2\\cdot\\rho\_M^2},\\quad\\frac{1}{\\sigma\_{\\beta M}^2\\cdot\\rho\_M^2})$
%[text] 
%[text] Поскольку на первом такте дальности $\\rho\_i$ неизвестны, метод WLLS реализуется как двухшаговый алгоритм: первичные дальности вычисляются от грубой предварительной засечки координат голого LLS.
%[text] 
%[text] ## 2. СТРОГИЙ ВЫВОД ВЗВЕШЕННЫХ ЛИНЕЙНЫХ УРАВНЕНИЙ СВЯЗИ (СТРОКИ МНК)
%[text] 
%[text] Линейный взвешенный метод (WLLS) требует преобразования нелинейных уравнений связи к виду взвешенной линейной системы нормальных уравнений $H\\cdot\\mathbf{X}=b$, где каждая строка нормируется на СКО промаха на местности $\\sigma\\cdot\\rho\_i$.
%[text] 
%[text] ### 2.1. Аналитический вывод строки горизонтального канала (Азимут $\\alpha\_i$)
%[text] Из определения азимута $\\alpha\_i$ и деления на линейный шум следует:
%[text] $\\frac{\\sin\\alpha\_i}{\\sigma\_{\\alpha i}\\cdot\\rho\_i}\\cdot x-\\frac{\\cos\\alpha\_i}{\\sigma\_{\\alpha i}\\cdot\\rho\_i}\\cdot y=\\frac{\\sin\\alpha\_i\\cdot x\_{si}-\\cos\\alpha\_i\\cdot y\_{si}}{\\sigma\_{\\alpha i}\\cdot\\rho\_i}$
%[text] 
%[text] Данное уравнение определяет **ПЕРВУЮ ВЗВЕШЕННУЮ МНК-СТРОКУ** (азимутальную) ядра `wlls_position.m`:
%[text] $H(2i-1,1)=\\frac{\\sin\\alpha\_i}{\\sigma\_{\\alpha i}\\cdot\\rho\_i}$
%[text] $H(2i-1,2)=\\frac{-\\cos\\alpha\_i}{\\sigma\_{\\alpha i}\\cdot\\rho\_i}$
%[text] $H(2i-1,3)=0$
%[text] $b(2i-1,1)=\\frac{\\sin\\alpha\_i\\cdot x\_{si}-\\cos\\alpha\_i\\cdot y\_{si}}{\\sigma\_{\\alpha i}\\cdot\\rho\_i}$
%[text] 
%[text] ### 2.2. Аналитический вывод строки вертикального канала (Угол места $\\beta\_i$)
%[text] Из определения угла места $\\beta\_i$ следует:
%[text] $-\\frac{\\cos\\alpha\_i\\sin\\beta\_i}{\\sigma\_{\\beta i}\\cdot\\rho\_i}\\cdot x-\\frac{\\sin\\alpha\_i\\sin\\beta\_i}{\\sigma\_{\\beta i}\\cdot\\rho\_i}\\cdot y+\\frac{\\cos\\beta\_i}{\\sigma\_{\\beta i}\\cdot\\rho\_i}\\cdot z=\\frac{-\\cos\\alpha\_i\\sin\\beta\_i\\cdot x\_{si}-\\sin\\alpha\_i\\sin\\beta\_i\\cdot y\_{si}+\\cos\\beta\_i\\cdot z\_{si}}{\\sigma\_{\\beta i}\\cdot\\rho\_i}$
%[text] 
%[text] Данное уравнение определяет **ВТОРУЮ ВЗВЕШЕННУЮ МНК-СТРОКУ** (вертикальную) ядра `wlls_position.m`:
%[text] $H(2i,1)=\\frac{-\\cos\\alpha\_i\\sin\\beta\_i}{\\sigma\_{\\beta i}\\cdot\\rho\_i}$
%[text] $H(2i,2)=\\frac{-\\sin\\alpha\_i\\sin\\beta\_i}{\\sigma\_{\\beta i}\\cdot\\rho\_i}$
%[text] $H(2i,3)=\\frac{\\cos\\beta\_i}{\\sigma\_{\\beta i}\\cdot\\rho\_i}$
%[text] $b(2i,1)=\\frac{-\\cos\\alpha\_i\\sin\\beta\_i\\cdot x\_{si}-\\sin\\alpha\_i\\sin\\beta\_i\\cdot y\_{si}+\\cos\\beta\_i\\cdot z\_{si}}{\\sigma\_{\\beta i}\\cdot\\rho\_i}$
%[text] 
%[text] Вычисление окончательного вектора координат цели в один такт без итераций:
%[text] $\\mathbf{X}\_{WLLS}=(H^TH)^{-1}H^T\\mathbf{b}$
%[text] 
%[text] ## 3. ДЕКАРТОВА КОВАРИАЦИЯ WLLS И ГЕОМЕТРИЯ ЭЛЛИПСА РАССЕЯНИЯ
%[text] 
%[text] Поскольку веса $\\frac{1}{\\sigma\\cdot\\rho\_i}$ уже аналитически интегрированы внутрь строк измерительной матрицы H на этапе линеаризации, функциональная ковариационная матрица шумов приведенной системы нормальных уравнений становится строго единичной: $R\_{normalized}=I$.
%[text] 
%[text] Закон линейного переноса погрешностей Гаусса-Маркова для ядра `wlls_covariance.m` сворачивает параметры и пространственный угол поворота эллипса рассеяния $1\\sigma$ в чистый сэндвич:
%[text] $K\_{WLLS}=(H^TH)^{-1}H^T\\cdot I\\cdot H(H^TH)^{-1}=(H^TH)^{-1}$
%[text] 
%[text] Таким образом, декартовы параметры рассеяния ТИС на местности полностью определяются оператором, обратным матрице нормальных уравнений взвешенной системы:
%[text] $\\sigma\_x=\\sqrt{K\_{WLLS}(1,1)},\\quad\\sigma\_y=\\sqrt{K\_{WLLS}(2,2)},\\quad\\sigma\_z=\\sqrt{K\_{WLLS}(3,3)}$
%[text] 
%[text] ## 4. ФИЗИЧЕСКИЙ АНАЛИЗ ПОВЕДЕНИЯ МЕТОДА НА РАВНОТОЧНОМ ШУМЕ
%[text] 
%[text] Рассмотрим работу WLLS на траверзе центра креста при одинаковом приборном шуме постов $\\sigma\_{\\alpha i}=\\sigma\_{\\beta i}=\\sigma\_{const}$.
%[text] 
%[text] Из-за деления строк на индивидуальные дальности $\\rho\_i$ структура нормальных уравнений WLLS кардинально отличается от голого LLS. Метод искусственно занижает информационный вес дальних фланговых станций. На равноточном шуме декартовы графики LLS и WLLS не будут близнецами, так как WLLS деформирует геометрию эллипса рассеяния, убирая паразитный вклад перекошенных шумом фланговых плоскостей связи.
%[text] 
%[text] Оценка дальности по оси OY взвешивается по дальномерным плечам, снижая величину тригонометрического скоса и частично компенсируя продольное Bias-сжатие к измерительной базе ТИС.

