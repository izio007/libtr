function [status, K_cart] = lls_covariance(P, alpha, beta, var_alpha, var_beta, lambda_est)
% =========================================================================
% CORE MATH KERNEL: DE CARTESIAN COVARIANCE FOR LINEAR LEAST SQUARES (LLS)
% SYSTEM MATRIX CONTEXT: EXACT MULTIDIMENSIONAL GAUSS-MARKOV SANDWICH
%
% PURPOSE:
%   Расчет ПОЛНОЙ декартовой ковариационной матрицы погрешностей LLS
%   размерности [3 x 3] под текущую пачку измерений в абсолютных метрах земли ENU. 
%   Учитывает нелинейное проникновение флуктуаций датчиков постов в структуру МНК-строк.
%   Сохраняет все взаимные корреляционные моменты и пространственные скосы осей.
%
% INPUT ARGUMENTS:
%   P          - Матрица координат постов ТИС, размер [3 x M], метры.
%   alpha      - Вектор зашумленных азимутов цели, размер [M x 1], радианы.
%   beta       - Вектор зашумленных углов места цели, размер [M x 1], радианы.
%   var_alpha  - Вектор дисперсий шума азимута постов, размер [M x 1], рад^2.
%   var_beta   - Вектор дисперсий шума угла места постов, размер [M x 1], рад^2.
%   lambda_est - Рассчитанный декартов вектор координат [X; Y; Z] из lls_position, метры.
%
% OUTPUT ARGUMENTS:
%   status     - Код завершения операции (Выходной регистр Си-модуля):
%                0: Успешный расчет ковариации, ранг информационной жесткости удержан.
%                1: Недостаточно информации для МНК (число активных постов M < 2).
%                2: Численное вырождение нормальных уравнений (rcond < eps). Матрица K_cart из NaN.
%   K_cart     - Полная декартова ковариационная матрица погрешностей ТИС, размер [3 x 3],
%                ед. изм.: метры^2. Усечение до диагональных компонент запрещено.
%
% ATTENTION (ЭШЕЛОН Б / ЗОНА КРАХА):
%   Ввиду отсутствия априорного знания об истинных координатах объекта, 
%   линеаризация сэндвича Гаусса-Маркова вынужденно выполняется относительно 
%   рантайм-оценки lambda_est из lls_position. 
%   На дальних рубежах (450 км) котангенсный Bias линейного метода приведет 
%   к искусственному занижению расчетных плеч дальностей rho_sq, что порождает 
%   систематическое занижение компонент матрицы K_cart относительно реального 
%   эмпирического рассеяния точек. Данное расхождение является врожденным 
%   ограничением метода LLS и подлежит исследованию.
%
% COMPILER ARCHITECTURE REQUIREMENT (GCC / ANSI C99):
%   - Категорически исключить динамическую аллокацию ОЗУ (malloc). Matrix buffers строго double.
%   - Расчет ковариационной матрицы погрешностей выполняется по полной многомерной формуле сэндвича.
%   - Проверка обусловленности выполняется по машинному нулю без SVD-маскировки и регуляризаций.
% =========================================================================

K_cart = NaN(3, 3);
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

H = zeros(2 * M, 3);
R_meters = zeros(2 * M, 2 * M);
x = lambda_est(1); y = lambda_est(2); z = lambda_est(3);

% 2. СБОРКА СТРУКТУРНЫХ МАТРИЦ СИСТЕМЫ И ТЕНЗОРА ОШИБОК НА МЕСТНОСТИ
for i = 1:M
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    
    % Точное воспроизведение измерительной матрицы H Слоя А
    H(2*i-1, 1) = sa;
    H(2*i-1, 2) = -ca;
    H(2*i-1, 3) = 0;
    
    H(2*i, 1) = -ca * sb;
    H(2*i, 2) = -sa * sb;
    H(2*i, 3) = cb;
    
    % Истинное пространственное плечо рычага от оцененной точки lambda_est до i-го поста ТИС
    rho_sq = (x - xs)^2 + (y - ys)^2 + (z - zs)^2;
    if rho_sq < 1e-3, rho_sq = 1e-3; end
    
    % Линейный разлет углового шума, перенесенный на местность (Рычаг промаха в метрах^2)
    R_meters(2*i-1, 2*i-1) = var_alpha(i) * rho_sq;
    R_meters(2*i,   2*i)   = var_beta(i) * rho_sq;
end

AtA = H.' * H;

% 3. АБСОЛЮТНАЯ АНАЛИТИЧЕСКАЯ ЧЕСТНОСТЬ ПО МАШИННОМУ НУЛЮ DOUBLE
if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
    status = 2; return; % Мгновенный аналитический отмах при потере ранга жесткости
end

% 4. ВЫЧИСЛЕНИЕ СТРОГОГО МНОГОМЕРНОГО СЭНДВИЧА ГАУССА-МАРКОВА С ПРИОРИТЕТНЫМИ СКОБКАМИ ОЗУ
InvAtA = inv(AtA);
K_cart = InvAtA * (H.' * R_meters * H) * InvAtA;
status = 0;
end
