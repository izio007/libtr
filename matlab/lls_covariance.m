function [status, std_X, std_Y, std_Z] = lls_covariance(P, alpha, beta, var_alpha, var_beta, lambda)
% =========================================================================
% CORE MATH KERNEL: DE CARTESIAN COVARIANCE FOR LINEAR LEAST SQUARES (LLS)
% SYSTEM MATRIX CONTEXT: DIFFERENTIAL ERROR PROPAGATION DIAGRAM (WITH RANGE)
%
% PURPOSE: 
%   Расчет декартовой ковариационной матрицы погрешностей LLS (параметров 
%   и угла поворота эллипса рассеяния по уровню 1 сигма) с учетом переноса 
%   углового приборного шума на квадраты дальностей до постов ТИС.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат постов ТИС, размер [3 x M], метры.
%   alpha     - Вектор азимутов цели, размер [M x 1], радианы (от оси OX).
%   beta      - Вектор углов места цели, размер [M x 1], радианы (от плоскости XOY).
%   var_alpha - Вектор дисперсий шума азимута датчиков, размер [M x 1], рад^2.
%   var_beta  - Вектор дисперсий шума угла места датчиков, размер [M x 1], рад^2.
%   lambda    - УЖЕ РАССЧИТАННЫЙ на текущем такте декартов вектор координат 
%               цели [X; Y; Z] из ОЗУ (исключает повторный вызов lls_position), метры.
%
% OUTPUT ARGUMENTS:
%   status - Код завершения операции (Выходной регистр Си-модуля):
%            0: Успешный расчет ковариационной матрицы.
%            1: Недостаточно информации для МНК (M < 2).
%            2: Геометрическое вырождение, детерминант ушел в машинный ноль.
%   std_X, std_Y, std_Z - СКО декартовых компонент положения цели, метры.
% =========================================================================

std_X = NaN; std_Y = NaN; std_Z = NaN;
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

H = zeros(2*M, 3);
R = zeros(2*M, 2*M); % Дифференциальная матрица приборного шума в метрах

x = lambda(1); y = lambda(2); z = lambda(3);

% 2. СБОРКА ИЗМЕРИТЕЛЬНЫХ МАТРИЦ (БАЗИС OX С УЧЕТОМ ДИФФЕРЕНЦИАЛА ДАЛЬНОСТИ)
for i = 1:M
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    
    % Вычисление квадрата расстояния от готовой засечки до i-го поста ТИС
    rho_sq = (x - xs)^2 + (y - ys)^2 + (z - zs)^2;
    if rho_sq < 1e-3, rho_sq = 1e-3; end
    
    % Линеаризованная строка азимута ТИС (от оси OX)
    H(2*i-1, 1) = sa;
    H(2*i-1, 2) = -ca;
    H(2*i-1, 3) = 0;
    
    % Ошибка по производным: угловая дисперсия переносится в линейные метры
    R(2*i-1, 2*i-1) = var_alpha(i) * rho_sq;
    
    % Линеаризованная строка угла места ТИС (ИСТИННЫЙ ЗНАК ТИС: -ca*sb, -sa*sb, cb)
    H(2*i, 1) = -ca * sb;
    H(2*i, 2) = -sa * sb;
    H(2*i, 3) = cb;
    
    % Ошибка по производным: дисперсия угла места переносится в линейные метры
    R(2*i, 2*i) = var_beta(i) * rho_sq;
end

AtA = H.' * H;

% 3. ЧЕСТНЫЙ АНАЛИТИЧЕСКИЙ ОТКАЗ: если определитель ушел в машинный ноль
if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
    status = 2; return;
end

% 4. ПЕРЕНОС ОШИБОК ПО СТРОГОМУ ЗАКОНУ ГАУССА-МАРКОВА ДЛЯ ПОВОРОТА ЭЛЛИПСА
inv_AtA = inv(AtA);
K_lls = inv_AtA * (H.' * R * H) * inv_AtA;

% 5. ИЗВЛЕЧЕНИЕ ПАРАМЕТРОВ ОПИСАННОГО ДЕКАРТОВА БОКСА ВОКРУГ ЭЛЛИПСОИДА РАССЕЯНИЯ
std_X = sqrt(K_lls(1, 1));
std_Y = sqrt(K_lls(2, 2));
std_Z = sqrt(K_lls(3, 3));
status = 0;
end
