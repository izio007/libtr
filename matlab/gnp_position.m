function [status, lambda] = gnp_position(P, alpha, beta, var_alpha, var_beta)
% =========================================================================
% CORE MATH KERNEL: NONLINEAR GAUSS-NEWTON POLAR INVARIANT ESTIMATION (GNP)
% SYSTEM MATRIX CONTEXT: METRIC SI-CANON WITH DYNAMIC LINEARIZATION UPDATE
%
% PURPOSE:
%   Итерационный нелинейный метод Гаусса-Ньютона в полярно-инвариантном 
%   пространстве параметров (GNP). Выполняет прецизионный поиск оценки 
%   сферического вектора состояния цели относительно полюса сети X_0 
%   строго в абсолютных метрах и радианах СИ без применения масштабирующих щитов.
%   Предназначен для фиксации момента геометрического краха разрядной сетки.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат измерительных постов ТИС, размер [3 x M], метры.
%               Строки соответствуют декартовым осям [x_si; y_si; z_si] в локальной СК ENU.
%   alpha     - Вектор зашумленных азимутов цели, размер [M x 1], радианы.
%               Отсчет ведется от положительного направления оси OX против часовой стрелки.
%   beta      - Вектор зашумленных углов места цели, размер [M x 1], радианы.
%               Отсчет ведется от горизонтальной плоскости XOY вверх в диапазоне [-pi/2; pi/2].
%   var_alpha - Вектор дисперсий шума каналов азимута постов, размер [M x 1], рад^2.
%               (В Эшелоне А зарезервирован для интерфейсной сквозной совместимости).
%   var_beta  - Вектор дисперсий шума каналов угла места постов, размер [M x 1], рад^2.
%               (В Эшелоне А зарезервирован для интерфейсной сквозной совместимости).
%
% OUTPUT ARGUMENTS:
%   status    - Код завершения вычислительной операции (Выходной аналитический признак):
%               0: Успешный расчет, ранг измерительной матрицы удержан, сходимость достигнута.
%               1: Недостаточно информации для МНК (число активных постов измерительной сети M < 2).
%               2: Геометрическое вырождение, критическое падение ранга матрицы нормальных
%                  уравнений (rcond < eps), либо расходимость процесса за max_iter шагов.
%   lambda    - Рассчитанный декартов вектор координат объекта [X; Y; Z] на земле, метры.
%               При status != 0 возвращает строго [NaN; NaN; NaN].
%
% COMPILER ARCHITECTURE REQUIREMENT (ANSI C99 COMPLIANCE):
%   - Исключить динамическое выделение памяти в процессе вычислений. 
%   - Начальное приближение итератора извлекается из равноточного ядра lls_position.
%   - Все тригонометрические инварианты линеаризуются строго от инвариантной оси OX.
%   - Проверка обусловленности выполняется по машинному нулю без регуляризаций.
% =========================================================================

lambda = [NaN; NaN; NaN];
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

% Вычисление координат инвариантного полюса системы (центра тяжести постов ТИС)
X_0 = mean(P, 2);
x0 = X_0(1); y0 = X_0(2); z0 = X_0(3);

% 2. СТАРТОВАЯ ЛИНЕЙНАЯ ЗАСЕЧКА (WLLS) ДЛЯ ОПРЕДЕЛЕНИЯ ТОЧКИ ПЕРВОГО ШАГА ИТЕРАЦИЙ
H_init = zeros(2*M, 3);
b_init = zeros(2*M, 1);

for i = 1:M
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    
    H_init(2*i-1, :) = [sa, -ca, 0];
    b_init(2*i-1, 1) = sa*xs - ca*ys;
    
    H_init(2*i, :)   = [-ca*sb, -sa*sb, cb];
    b_init(2*i, 1)   = -ca*sb*xs - sa*sb*ys + cb*zs;
end

AtA_init = H_init.' * H_init;
if rcond(AtA_init) < 2.2204e-16 || isnan(rcond(AtA_init))
    status = 2; return; % Мгновенный аналитический отмах при вырождении старта
end
lambda_lls = AtA_init \ (H_init.' * b_init);

% Перевод начальной декартовой засечки в исходный полярный вектор состояния Y (в метрах СИ)
dx_init = lambda_lls(1) - x0;
dy_init = lambda_lls(2) - y0;
dz_init = lambda_lls(3) - z0;

r_h_init = sqrt(dx_init^2 + dy_init^2);
alpha_0  = atan2(dy_init, dx_init);
beta_0   = atan2(dz_init, r_h_init);
R_0      = sqrt(dx_init^2 + dy_init^2 + dz_init^2);

if R_0 < 1e-3, R_0 = 1e-3; end

max_iter = 100;
epsilon_angle = 1e-5; % Уставной допуск на останов по угловым невязкам ТИС
converged = false;

% 3. ИТЕРАЦИОННЫЙ ПРОЦЕСС ОПТИМИЗАЦИИ В СТЕРИЛЬНОМ СИ-ПРОСТРАНСТВЕ (РАВНОТОЧНЫЙ МНК)
for iter = 1:max_iter
    
    % Динамическое обновление тригонометрических инвариантов на входе в шаг
    ca0 = cos(alpha_0); sa0 = sin(alpha_0);
    cb0 = cos(beta_0);  sb0 = sin(beta_0);
    
    % Аналитический точный переход к декартовым координатам на прямоугольной земле ENU
    x = x0 + R_0 * cb0 * ca0;
    y = y0 + R_0 * cb0 * sa0;
    z = z0 + R_0 * sb0;
    
    J = zeros(2 * M, 3);
    residual = zeros(2 * M, 1);
    
    for i = 1:M
        xs = P(1, i); ys = P(2, i); zs = P(3, i);
        
        % Пространственные приращения визирования в абсолютных метрах земли
        dx_i = x - xs;
        dy_i = y - ys;
        dz_i = z - zs;
        
        r_h_i_sq = dx_i^2 + dy_i^2;
        r_h_i = sqrt(r_h_i_sq);
        if r_h_i < 1e-3, r_h_i = 1e-3; r_h_i_sq = 1e-6; end
        
        r_i_sq = r_h_i_sq + dz_i^2;
        r_i = sqrt(r_i_sq);
        if r_i < 1e-3, r_i = 1e-3; r_i_sq = 1e-6; end
        
        % Прогнозируемые угловые пеленги i-го поста
        alpha_pred = atan2(dy_i, dx_i);
        beta_pred  = atan2(dz_i, r_h_i);
        
        % Расчет вектора невязок с тригонометрическим приведением фазы к [-pi; pi]
        ang_res_a = alpha(i) - alpha_pred;
        ang_res_a = atan2(sin(ang_res_a), cos(ang_res_a));
        
        ang_res_b = beta(i) - beta_pred;
        ang_res_b = atan2(sin(ang_res_b), cos(ang_res_b));
        
        residual(2*i-1, 1) = ang_res_a;
        residual(2*i,   1) = ang_res_b;
        
        % Сборка Якобиана по Chain Rule строго в метрах СИ (Слой А Математического паспорта)
        % Производные по азимуту, углу места и радиальной дальности в метрах R_0
        J(2*i-1, 1) = (R_0 * cb0 * (dx_i * ca0 + dy_i * sa0)) / r_h_i_sq;
        J(2*i-1, 2) = (R_0 * sb0 * (dy_i * ca0 - dx_i * sa0)) / r_h_i_sq;
        J(2*i-1, 3) = (cb0 * (dx_i * sa0 - dy_i * ca0)) / r_h_i_sq;
        
        J(2*i, 1)   = (R_0 * dz_i * cb0 * (dx_i * sa0 - dy_i * ca0)) / (r_i_sq * r_h_i);
        J(2*i, 2)   = (R_0 * (r_h_i_sq * cb0 + dz_i * sb0 * (dx_i * ca0 + dy_i * sa0))) / (r_i_sq * r_h_i);
        J(2*i, 3)   = (r_h_i_sq * sb0 - dz_i * cb0 * (dx_i * ca0 + dy_i * sa0)) / (r_i_sq * r_h_i);
    end
    
    % Формирование информационной жесткости Гаусса-Ньютона без весовых коэффициентов
    AtA = J.' * J;
    
    % Проверка обусловленности линеаризованной системы по машинному нулю вещественной сетки
    if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
        status = 2; return; % Полное и бескомпромиссное обнажение вырождения ранга
    end
    
    % Вычисление вектора шага полярного приращения
    delta_Y = AtA \ (J.' * residual);
    
    % Проверка канонического критерия останова ТИС по стабильности измерительного функционала
    if max(abs(J * delta_Y)) < epsilon_angle
        converged = true;
    end
    
    % Обновление полярных компонент состояния
    alpha_0 = alpha_0 + delta_Y(1);
    beta_0  = beta_0  + delta_Y(2);
    R_0     = R_0     + delta_Y(3);
    
    % Принудительная тригонометрическая редукция фазы азимута на границе +-pi
    alpha_0 = atan2(sin(alpha_0), cos(alpha_0));
    
    if converged
        break;
    end
end

if ~converged
    status = 2; return;
end

% Итоговый аналитически точный пересчет в декартовы метры земли ENU для приклада ТИС
lambda = [x0 + R_0 * cos(beta_0) * cos(alpha_0); ...
          y0 + R_0 * cos(beta_0) * sin(alpha_0); ...
          z0 + R_0 * sin(beta_0)];
status = 0;
end
