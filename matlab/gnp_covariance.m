function [status, K_cart] = gnp_covariance(P, alpha, beta, var_alpha, var_beta, lambda)
% =========================================================================
% CORE MATH KERNEL: DE CARTESIAN COVARIANCE FOR GAUSS-NEWTON POLAR INVARIANT (GNP)
% SYSTEM MATRIX CONTEXT: EXACT FISHER INFORMATION MATRIX WITH NORMALISED TENSOR
%
% PURPOSE:
%   Расчет полной декартовой ковариационной матрицы погрешностей ТИС размерности 
%   [3 x 3] под текущую пачку измерений в абсолютных метрах земли ENU. Вводит 
%   в явном виде матрицу весов Гаусса-Маркова W и реализует нормированный 
%   по R_0 базис Якоби для предотвращения численного выжигания разрядной сетки вычислителя.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат измерительных постов ТИС, размер [3 x M], метры.
%               Строки соответствуют декартовым осям [x_si; y_si; z_si] в локальной СК ENU.
%   alpha     - Вектор зашумленных азимутов цели, размер [M x 1], радианы.
%               Отсчет ведется от положительного направления оси OX против часовой стрелки.
%   beta      - Вектор зашумленных углов места цели, размер [M x 1], радианы.
%               Отсчет ведется от горизонтальной плоскости XOY вверх в диапазоне [-pi/2; pi/2].
%   var_alpha - Паспортный вектор дисперсий шума каналов азимута постов, размер [M x 1], рад^2.
%   var_beta  - Паспортный вектор дисперсий шума каналов угла места постов, размер [M x 1], рад^2.
%   lambda    - Рассчитанный декартов вектор координат цели [X; Y; Z], полученный 
%               из ядра gnp_position при успешной сходимости по норме шага, метры.
%
% OUTPUT ARGUMENTS:
%   status    - Код завершения вычислительной операции (Выходной аналитический признак):
%               0: Успешный расчет ковариации, информационная матрица Фишера обратима.
%               1: Недостаточно информации для МНК (число активных постов измерительной сети M < 2).
%               2: Геометрическое вырождение, критическое падение ранга матрицы нормальных
%                  уравнений (rcond < eps). Матрица K_cart возвращается как [3 x 3] из NaN.
%   K_cart    - Полная инвариантная декартова ковариационная матрица погрешностей ТИС,
%               размер [3 x 3], ед. изм.: метры^2. Содержит все перекрестные корреляционные
%               моменты и пространственные скосы осей эллипсоида рассеяния.
%
% COMPILER ARCHITECTURE REQUIREMENT (ANSI C99 COMPLIANCE):
%   - Исключить динамическое выделение памяти в процессе вычислений.
%   - Расчет ковариационной матрицы погрешностей выполняется по полной многомерной формуле сэндвича.
%   - Проверка обусловленности выполняется по машинному нулю без регуляризаций.
% =========================================================================

K_cart = NaN(3, 3);
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

% Вычисление координат инвариантного полюса системы (центра тяжести постов ТИС)
X_0 = mean(P, 2);
x0 = X_0(1); y0 = X_0(2); z0 = X_0(3);

% Извлечение декартовых координат финальной точки сходимости Слоя А
x = lambda(1); y = lambda(2); z = lambda(3);

% Перевод декартовых координат точки в сферический triplet состояния Y (в метрах СИ)
dx_ref = x - x0;
dy_ref = y - y0;
dz_ref = z - z0;

r_h_ref = sqrt(dx_ref^2 + dy_ref^2);
alpha_0 = atan2(dy_ref, dx_ref);
beta_0  = atan2(dz_ref, r_h_ref);
R_0     = sqrt(dx_ref^2 + dy_ref^2 + dz_ref^2);

if R_0 < 1e-3, R_0 = 1e-3; end

% Вычисление тригонометрических инвариантов базового состояния
ca0 = cos(alpha_0); sa0 = sin(alpha_0);
cb0 = cos(beta_0);  sb0 = sin(beta_0);

J = zeros(2 * M, 3);
W = zeros(2 * M, 2 * M);

% 2. СБОРКА АНАЛИТИЧЕСКОГО МЕТРИЧЕСКОГО ЯКОБИАНА И МАТРИЦЫ ВЕСОВ ГАУССА-МАРКОВА
for i = 1:M
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    
    % Пространственные приращения визирования в абсолютных метрах земли
    dx_i = x - xs;
    dy_i = y - ys;
    dz_i = z - zs;
    
    r_h_i_sq = dx_i^2 + dy_i^2;
    r_h_i = sqrt(r_h_i_sq);
    if r_h_i < 1e-3, r_h_i = 1e-3; r_h_i_sq = 1e-6; end
    
    r_i_sq = r_h_i_sq + dz_i^2;
    r_i = sqrt(r_i_sq);
    if r_i < 1e-3, r_i = 1e-3; r_i_sq = 1e-6; end
    
    % Весовая матрица Гаусса-Маркова из измерительного пространства углов (размерность [1/рад^2])
    W(2*i-1, 2*i-1) = 1.0 / var_alpha(i);
    W(2*i,   2*i)   = 1.0 / var_beta(i);
    
    % Дифференцирование по каноническому метрическому вектору Y = [alpha_0, beta_0, R_0] (Слой А)
    J(2*i-1, 1) = (R_0 * cb0 * (dx_i * ca0 + dy_i * sa0)) / r_h_i_sq;
    J(2*i-1, 2) = (R_0 * sb0 * (dy_i * ca0 - dx_i * sa0)) / r_h_i_sq;
    J(2*i-1, 3) = (cb0 * (dx_i * sa0 - dy_i * ca0)) / r_h_i_sq;
    
    J(2*i, 1)   = (R_0 * dz_i * cb0 * (dx_i * sa0 - dy_i * ca0)) / (r_i_sq * r_h_i);
    J(2*i, 2)   = (R_0 * (r_h_i_sq * cb0 + dz_i * sb0 * (dx_i * ca0 + dy_i * sa0))) / (r_i_sq * r_h_i);
    J(2*i, 3)   = (r_h_i_sq * sb0 - dz_i * cb0 * (dx_i * ca0 + dy_i * sa0)) / (r_i_sq * r_h_i);
end

% Формирование информационной матрицы жесткости Фишера с весами Гаусса-Маркова
AtA = J.' * W * J;

% 3. ОЦЕНКА ЧИСЛЕННОГО ВЫРОЖДЕНИЯ СТРОГО ПО МАШИННОМУ НУЛЮ ВЕЩЕСТВЕННОЙ СЕТКИ
if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
    status = 2; return; % Полное и бескомпромиссное обнажение вырождения ранга
end

% Нахождение исходного полярного тензора погрешностей K_polar
K_polar = inv(AtA);

% 4. ПРЕЦИЗИОННЫЙ БЕЗРАЗМЕРНЫЙ РАЗВОРOТ ЯКОБИ (ЗАЩИТА РАЗРЯДНОЙ СЕТКИ ОТ ВЫЖИГАНИЯ)
% Симметричный пересчет ковариации через нормировочную матрицу M_norm = diag(R_0, R_0, 1)
K_polar_norm = K_polar;
K_polar_norm(1, 1) = K_polar(1, 1) * (R_0^2);
K_polar_norm(1, 2) = K_polar(1, 2) * (R_0^2);
K_polar_norm(2, 1) = K_polar(2, 1) * (R_0^2);
K_polar_norm(2, 2) = K_polar(2, 2) * (R_0^2);
K_polar_norm(1, 3) = K_polar(1, 3) * R_0;
K_polar_norm(3, 1) = K_polar(3, 1) * R_0;
K_polar_norm(2, 3) = K_polar(2, 3) * R_0;
K_polar_norm(3, 2) = K_polar(3, 2) * R_0;

% Безразмерный нормированный по R_0 базис Якоби обратного перехода
J_polar2cart_norm = [ -cb0 * sa0,  -sb0 * ca0,  cb0 * ca0; ...
                       cb0 * ca0,  -sb0 * sa0,  cb0 * sa0; ...
                       0,           cb0,        sb0 ];

% Формирование финального декартова тензора в абсолютных метрах земли ENU
K_cart = J_polar2cart_norm * K_polar_norm * J_polar2cart_norm.';
status = 0;
end
