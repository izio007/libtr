%[text] ## 1. ГЕОМЕТРИЧЕСКИЙ БАЗИС И ИНВАРЯНТЫ ИЗМЕРИТЕЛЬНОЙ ЗАДАЧИ ТИС
%[text]
%[text] Триангуляционно-Измерительная Система (ТИС) осуществляет пассивную пеленгацию цели с координатами:
%[text] $\mathbf{X}=[x,y,z]^T$
%[text]
%[text] Сеть состоит из M базовых постов с известными декартовыми координатами:
%[text] $\mathbf{X}_{si}=[x_{si},y_{si},z_{si}]^T,\\quad i=1,\\dots,M$
%[text]
%[text] Вектор дальности (прямой визирный луч) из i-го измерительного поста в цель задается приращениями:
%[text] $\Delta x_i=x-x_{si}$
%[text] $\Delta y_i=y-y_{si}$
%[text] $\Delta z_i=z-z_{si}$
%[text]
%[text] Проекция визирного луча на горизонтальную плоскость XOY (продольная дальность):
%[text] $r_{xy,i}=\sqrt{\Delta x_i^2+\Delta y_i^2}$
%[text]
%[text] Полная пространственная дальность до цели составляет:
%[text] $r_i=\sqrt{\Delta x_i^2+\Delta y_i^2+\Delta z_i^2}$
%[text]
%[text] В соответствии со строгим законом измерительного базиса ТИС, все углы откладываются от единых реперов классической тригонометрии Декарта:
%[text] * **Азимут** ($\alpha_i$): Отсчитывается в горизонтальной плоскости строго от положительного направления оси OX против часовой стрелки в диапазоне $[0;2\pi)$.
%[text] * **Угол места** ($\beta_i$): Отсчитывается в вертикальной плоскости строго от горизонтальной плоскости XOY вверх в диапазоне $[-\pi/2;\pi/2]$.
%[text]
%[text] Связь между углами пеленгации и декартовыми координатами:
%[text] $\alpha_i=\text{atan2}(\Delta y_i,\Delta x_i)$
%[text] $\beta_i=\text{atan2}(\Delta z_i,r_{xy,i})$
%[text]
%[text] ## 2. СТРОГИЙ ВЫВОД ЛИНЕЙНЫХ УРАВНЕНИЙ СВЯЗИ (СТРОКИ МНК)
%[text]
%[text] Линейный метод (LLS) требует преобразования нелинейных уравнений связи к виду линейной системы нормальных уравнений $H\cdot\mathbf{X}=b$.
%[text]
%[text] ### 2.1. Аналитический вывод строки горизонтального канала (Азимут $\alpha_i$)
%[text] Из определения азимута $\alpha_i$ следует:
%[text] $\tan\alpha_i=\frac{\Delta y_i}{\Delta x_i}=\frac{y-y_{si}}{x-x_{si}}$
%[text]
%[text] Раскрываем пропорцию, избавляясь от нелинейного знаменателя в ОЗУ:
%[text] $(x-x_{si})\sin\alpha_i=(y-y_{si})\cos\alpha_i$
%[text] $x\sin\alpha_i-x_{si}\sin\alpha_i=y\cos\alpha_i-y_{si}\cos\alpha_i$
%[text]
%[text] Группируем неизвестные координаты цели (x, y) в левой части:
%[text] $\sin\alpha_i\cdot x-\cos\alpha_i\cdot y=\sin\alpha_i\cdot x_{si}-\cos\alpha_i\cdot y_{si}$
%[text]
%[text] Данное уравнение определяет **ПЕРВУЮ МНК-СТРОКУ** (азимутальную) ядра `lls_position.m`:
%[text] $H(2i-1,1)=\sin\alpha_i$
%[text] $H(2i-1,2)=-\cos\alpha_i$
%[text] $H(2i-1,3)=0$
%[text] $b(2i-1,1)=\sin\alpha_i\cdot x_{si}-\cos\alpha_i\cdot y_{si}$
%[text]
%[text] ### 2.2. Аналитический вывод строки вертикального канала (Угол места $\beta_i$)
%[text] Из определения угла места $\beta_i$ следует:
%[text] $\tan\beta_i=\frac{\Delta z_i}{r_{xy,i}}\quad\rightarrow\quad\Delta z_i\cos\beta_i-r_{xy,i}\sin\beta_i=0$
%[text] $(z-z_{si})\cos\beta_i-r_{xy,i}\sin\beta_i=0$
%[text]
%[text] Продольная дальность $r_{xy,i}$ выражается через горизонтальные приращения:
%[text] $r_{xy,i}=\Delta x_i\cos\alpha_i+\Delta y_i\sin\alpha_i=(x-x_{si})\cos\alpha_i+(y-y_{si})\sin\alpha_i$
%[text]
%[text] Подставляем $r_{xy,i}$ в уравнение угла места:
%[text] $(z-z_{si})\cos\beta_i-[(x-x_{si})\cos\alpha_i+(y-y_{si})\sin\alpha_i]\sin\beta_i=0$
%[text]
%[text] Раскрываем скобки:
%[text] $z\cos\beta_i-z_{si}\cos\beta_i-x\cos\alpha_i\sin\beta_i+x_{si}\cos\alpha_i\sin\beta_i-y\sin\alpha_i\sin\beta_i+y_{si}\sin\alpha_i\sin\beta_i=0$
%[text]
%[text] Группируем неизвестные координаты цели (x, y, z) слева (**ВЕРИФИЦИРОВАННЫЙ ЗНАК ТИС**):
%[text] $-\cos\alpha_i\sin\beta_i\cdot x-\sin\alpha_i\sin\beta_i\cdot y+\cos\beta_i\cdot z=-\cos\alpha_i\sin\beta_i\cdot x_{si}-\sin\alpha_i\sin\beta_i\cdot y_{si}+\cos\beta_i\cdot z_{si}$
%[text]
%[text] Данное уравнение определяет **ВТОРУЮ МНК-СТРОКУ** (вертикальную) ядра `lls_position.m`:
%[text] $H(2i,1)=-\cos\alpha_i\sin\beta_i$
%[text] $H(2i,2)=-\sin\alpha_i\sin\beta_i$
%[text] $H(2i,3)=\cos\beta_i$
%[text] $b(2i,1)=-\cos\alpha_i\sin\beta_i\cdot x_{si}-\sin\alpha_i\sin\beta_i\cdot y_{si}+\cos\beta_i\cdot z_{si}$

%[text] ## 3. ГЕОМЕТРИЯ ЭЛЛИПСА ОШИБОК И ВЫВОД К КОВАРИАЦИИ LLS
%[text]
%[text] Плотность распределения вероятности ошибки ТИС описывается пространственным Гауссовым колоколом. Геометрический срез этого колокола на уровне одной сигмы ($1\sigma$) определяет **эллипсоид ошибок рассеяния**. Матрица ковариации жестко задает размеры его полуосей и пространственный угол наклона к измерительной базе ТИС.
%[text]
%[text] Оценка декартова вектора состояния ТИС определяется из нормальных уравнений:
%[text] $\mathbf{X}=(H^TH)^{-1}H^T\mathbf{b}$
%[text]
%[text] Поскольку в векторе свободных членов $\mathbf{b}$ жестко зашиты координаты постов ТИС в метрах, частные производные (ошибки по производным) вектора невязок по измеряемым углам пеленгации $\mathbf{y}=[\alpha_1,\beta_1,\dots,\alpha_M,\beta_M]^T$ физически возвращают дальности до станций:
%[text] $\frac{\partial b_{2i-1}}{\partial\alpha_i}=\cos\alpha_i\cdot x_{si}+\sin\alpha_i\cdot y_{si}\quad\rightarrow\quad\rho_i=x\cos\alpha_i+y\sin\alpha_i$
%[text]
%[text] Дифференциальный перенос некоррелированного углового шума приборов $R_{diag}=\text{diag}(\sigma_{\alpha i}^2,\sigma_{\beta i}^2)$ в линейный промах на местности (ширину эллипса в метрах) жестко зависит от плеча рычага — дальности до поста $\rho_i$. Это порождает масштабированную матрицу погрешностей в метрах:
%[text] $R_{meters}=\text{diag}(\sigma_{\alpha i}^2\cdot\rho_i^2,\quad\sigma_{\beta i}^2\cdot\rho_i^2)$
%[text]
%[text] По строгому закону переноса погрешностей Гаусса-Маркова, аналитическая структура ковариационного ядра `lls_covariance.m` перемножает тригонометрическую геометрию на линейный разлет эллипса:
%[text] $K_{LLS}=(H^TH)^{-1}H^T\cdot R_{meters}\cdot H(H^TH)^{-1}$
%[text]
%[text] Элементы по главной диагонали матрицы $K_{LLS}$ вычисляют параметры описанного декартова бокса вокруг повернутого эллипса ошибок, выдавая честные СКО для экрана ТИС:
%[text] $\sigma_x=\sqrt{K_{LLS}(1,1)},\quad\sigma_y=\sqrt{K_{LLS}(2,2)},\quad\sigma_z=\sqrt{K_{LLS}(3,3)}$

%[text] ## 4. ФИЗИЧЕСКИЙ АНАЛИЗ ТРИГОНОМЕТРИЧЕСКОГО СЖАТИЯ (BIAS LLS) НА ТРАВЕРЗЕ
%[text]
%[text] Рассмотрим критический случай, когда цель находится на траверзе центра измерительного креста ТИС ($X=0$) на огромном удалении ($Y=450$ км). Реперный пост расположен в начале координат ($x_s=0,y_s=0\rightarrow b=0$).
%[text]
%[text] Истинный геометрический азимут на север равен:
%[text] $\alpha_0=90^\circ=\frac{\pi}{2}\text{ рад}$
%[text]
%[text] При наличии углового шума датчиков n измеренный азимут равен:
%[text] $\alpha=90^\circ+n$
%[text]
%[text] Подставим зашумленный ракурс в первую азимутальную МНК-строку:
%[text] $\sin(90^\circ+n)\cdot x-\cos(90^\circ+n)\cdot y=0$
%[text]
%[text] Используя строгие тригонометрические формулы приведения:
%[text] $\sin(90^\circ+n)=\cos(n)$
%[text] $\cos(90^\circ+n)=-\sin(n)$
%[text]
%[text] Получаем линеаризованную строку связи для текущего зашумленного такта:
%[text] $\cos(n)\cdot x+\sin(n)\cdot y=0$
%[text]
%[text] Отсюда выразим оценку дальности по оси OY, которую пытается найти линейный метод LLS:
%[text] $y=-x\cdot\frac{\cos(n)}{\sin(n)}=-x\cdot\cot(n)$
%[text]
%[text] *ИНЖЕНЕРНЫЕ ВЫВОДЫ ИЗ АНАЛИЗА КОТАНГЕНСА:*
%[text]
%[text] 1. При отсутствии шума ($n=0$): $\cot(0)=\infty$. Система параллельна оси OY, продольная жесткость бесконечна, точная дальность находится за счет пересечения лучей.
%[text] 2. При включении шума ($\sigma=2.0^\circ$): Случайная величина шума n колеблется в диапазоне $[-6^\circ;+6^\circ]$ (правило трех сигм).
%[text] 3. Нелинейный зажим: Математическая функция котангенса в окрестности нуля ведет себя как гипербола $1/n$. При шуме $2.0^\circ$ ($0.0349$ рад) среднее absolute значение величины падает:
%[text] $\langle|\cot(n)|\rangle\approx\frac{1}{0.0349}\approx28.6$
%[text] 4. Физический крах: Из-за Гауссова шума в знаменателе котангенса строка связи теряет продольную жесткость, приобретая паразитную декартову связь. МНК-критерий ложно схлопывает дальность ближе к базе ТИС, порождая Bias в -308 км.

