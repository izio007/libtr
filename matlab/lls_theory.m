%[text] ## 1. ГЕОМЕТРИЧЕСКИЙ БАЗИС И ИНВАРЯНТЫ ИЗМЕРИТЕЛЬНОЙ ЗАДАЧИ ТИС
%[text] 
%[text] Триангуляционно-Измерительная Система (ТИС) осуществляет пассивную пеленгацию цели с координатами:
%[text] $\\mathbf{X}=\[x,y,z\]^T$
%[text] 
%[text] Сеть состоит из M базовых постов с известными декартовыми координатами:
%[text] $\\mathbf{X}\_{si}=\[x\_{si},y\_{si},z\_{si}\]^T,\\quad i=1,\\dots,M$
%[text] 
%[text] Вектор дальности (прямой визирный луч) из i-го измерительного поста в цель задается приращениями:
%[text] $\\Delta x\_i=x-x\_{si}$
%[text] $\\Delta y\_i=y-y\_{si}$
%[text] $\\Delta z_i=z-z\_{si}$
%[text] 
%[text] Проекция визирного луча на horizontalьную плоскость XOY (продольная дальность):
%[text] $r\_{xy,i}=\\sqrt{\\Delta x\_i^2+\\Delta y\_i^2}$
%[text] 
%[text] Полная пространственная дальность до цели составляет:
%[text] $r\_i=\\sqrt{\\Delta x\_i^2+\\Delta y\_i^2+\\Delta z\_i^2}$
%[text] 
%[text] В соответствии со строгим законом измерительного базиса ТИС, все углы откладываются от единых реперов классической тригонометрии Декарта:
%[text] * **Азимут** ($\alpha_i$): Отсчитывается в горизонтальной плоскости строго от положительного направления оси OX против часовой стрелки в диапазоне $[0;2\pi)$.
%[text] * **Угол места** ($\beta_i$): Отсчитывается в вертикальной плоскости строго от горизонтальной плоскости XOY вверх в диапазоне $[-\pi/2;\pi/2]$.
%[text] 
%[text] Связь между углами пеленгации и декартовыми координатами:
%[text] $\\alpha\_i=\\text{atan2}(\\Delta y\_i,\\Delta x\_i)$
%[text] $\\beta\_i=\\text{atan2}(\\Delta z\_i,r\_{xy,i})$
%[text] 
%[text] ## 2. СТРОГИЙ ВЫВОД ЛИНЕЙНЫХ УРАВНЕНИЙ СВЯЗИ (СТРОКИ МНК)
%[text] 
%[text] Линейный метод (LLS) требует преобразования нелинейных уравнений связи к виду линейной системы нормальных уравнений $H\\cdot\\mathbf{X}=b$.
%[text] 
%[text] ### 2.1. Аналитический вывод строки горизонтального канала (Азимут $\alpha_i$)
%[text] Из определения азимута $\alpha_i$ следует:
%[text] $\\tan\\alpha\_i=\\frac{\\Delta y\_i}{\\Delta x\_i}=\\frac{y-y\_{si}}{x-x\_{si}}$
%[text] 
%[text] Раскрываем пропорцию, избавляясь от нелинейного знаменателя в ОЗУ:
%[text] $(x-x\_{si})\\sin\\alpha\_i=(y-y\_{si})\\cos\\alpha\_i$
%[text] $x\\sin\\alpha\_i-x\_{si}\\sin\\alpha\_i=y\\cos\\alpha\_i-y\_{si}\\cos\\alpha\_i$
%[text] 
%[text] Группируем неизвестные координаты цели (x, y) в левой части:
%[text] $\\sin\\alpha\_i\\cdot x-\\cos\\alpha\_i\\cdot y=\\sin\\alpha\_i\\cdot x\_{si}-\\cos\\alpha\_i\\cdot y\_{si}$
%[text] 
%[text] Данное уравнение определяет **ПЕРВУЮ МНК-СТРОКУ** (азимутальную) ядра `lls_position.m`:
%[text] $H(2i-1,1)=\\sin\\alpha\_i$
%[text] $H(2i-1,2)=-\\cos\\alpha\_i$
%[text] $H(2i-1,3)=0$
%[text] $b(2i-1,1)=\\sin\\alpha\_i\\cdot x\_{si}-\\cos\\alpha\_i\\cdot y\_{si}$
%[text] 
%[text] ### 2.2. Аналитический вывод строки вертикального канала (Угол места $\beta_i$)
%[text] Из определения угла места $\beta_i$ следует:
%[text] $\\tan\\beta\_i=\\frac{\\Delta z\_i}{r\_{xy,i}}\\quad\\rightarrow\\quad\\Delta z\_i\\cos\\beta\_i-r\_{xy,i}\\sin\\beta\_i=0$
%[text] $(z-z\_{si})\\cos\\beta\_i-r\_{xy,i}\\sin\\beta\_i=0$
%[text] 
%[text] Продольная дальность $r\_{xy,i}$ выражается через горизонтальные приращения:
%[text] $r\_{xy,i}=\\Delta x\_i\\cos\\alpha\_i+\\Delta y\_i\\sin\\alpha\_i=(x-x\_{si})\\cos\\alpha\_i+(y-y\_{si})\\sin\\alpha\_i$
%[text] 
%[text] Подставляем $r\_{xy,i}$ в уравнение угла места:
%[text] $(z-z\_{si})\\cos\\beta\_i-\[(x-x\_{si})\\cos\\alpha\_i+(y-y\_{si})\\sin\\alpha\_i\]\\sin\\beta\_i=0$
%[text] 
%[text] Раскрываем скобки:
%[text] $z\\cos\\beta\_i-z\_{si}\\cos\\beta\_i-x\\cos\\alpha\_i\\sin\\beta\_i+x\_{si}\\cos\\alpha\_i\\sin\\beta\_i-y\\sin\\alpha\_i\\sin\\beta\_i+y\_{si}\\sin\\alpha\_i\\sin\\beta\_i=0$
%[text] 
%[text] Группируем неизвестные координаты цели (x, y, z) слева (**ВЕРИФИЦИРОВАННЫЙ ЗНАК ТИС**):
%[text] $-\\cos\\alpha\_i\\sin\\beta\_i\\cdot x-\\sin\\alpha\_i\\sin\\beta\_i\\cdot y+\\cos\\beta\_i\\cdot z=-\\cos\\alpha\_i\\sin\\beta\_i\\cdot x\_{si}-\\sin\\alpha\_i\\sin\\beta\_i\\cdot y\_{si}+\\cos\\beta\_i\\cdot z\_{si}$
%[text] 
%[text] Данное уравнение определяет **ВТОРУЮ МНК-СТРОКУ** (вертикальную) ядра `lls_position.m`:
%[text] $H(2i,1)=-\\cos\\alpha\_i\\sin\\beta\_i$
%[text] $H(2i,2)=-\\sin\\alpha\_i\\sin\\beta\_i$
%[text] $H(2i,3)=\\cos\\beta\_i$
%[text] $b(2i,1)=-\\cos\\alpha\_i\\sin\\beta\_i\\cdot x\_{si}-\\sin\\alpha\_i\\sin\\beta\_i\\cdot y\_{si}+\\cos\\beta\_i\\cdot z\_{si}$
%[text] 
%[text] ## 3. ГЕОМЕТРИЯ ЭЛЛИПСА ОШИБОК И ВЫВОД К КОВАРИАЦИИ LLS
%[text] 
%[text] Плотность распределения вероятности ошибки ТИС описывается пространственным Гауссовым колоколом. Геометрический срез этого колокола на уровне одной сигмы ($1\\sigma$) определяет **эллипсоид ошибок рассеяния**. Матрица ковариации жестко задает размеры его полуосей и пространственный угол наклона к измерительной базе ТИС.
%[text] 
%[text] Оценка декартова вектора состояния ТИС определяется из нормальных уравнений:
%[text] $\\mathbf{X}=(H^TH)^{-1}H^T\\mathbf{b}$
%[text] 
%[text] Поскольку в векторе свободных членов $\mathbf{b}$ жестко зашиты координаты постов ТИС в метрах, частные производные (ошибки по производным) вектора невязок по измеряемым углам пеленгации $\mathbf{y}=\[\\alpha\_1,\\beta\_1,\\dots,\\alpha\_M,\\beta\_M\]^T$ физически возвращают дальности до станций:
%[text] $\\frac{\\partial b\_{2i-1}}{\\partial\\alpha\_i}=\\cos\\alpha\_i\\cdot x\_{si}+\\sin\\alpha\_i\\cdot y_{si}\\quad\\rightarrow\\quad\\rho\_i=x\\cos\\alpha\_i+y\\sin\\alpha\_i$
%[text] 
%[text] Дифференциальный перенос некоррелированного углового шума приборов $R\_{diag}=\\text{diag}(\\sigma\_{\\alpha i}^2,\\sigma\_{\\beta i}^2)$ в линейный промах на местности (ширину эллипса в метрах) жестко зависит от плеча рычага — дальности до поста $\\rho\_i$. Это порождает масштабированную матрицу погрешностей в метрах:
%[text] $R\_{meters}=\\text{diag}(\\sigma\_{\\alpha i}^2\\cdot\\rho\_i^2,\\quad\\sigma\_{\\beta i}^2\\cdot\\rho\_i^2)$
%[text] 
%[text] По строгому закону переноса погрешностей Гаусса-Маркова, аналитическая структура ковариационного ядра `lls_covariance.m` перемножает тригонометрическую геометрию на линейный разлет эллипса:
%[text] $K\_{LLS}=(H^TH)^{-1}H^T\\cdot R\_{meters}\\cdot H(H^TH)^{-1}$
%[text] 
%[text] Элементы по главной диагонали матрицы $K\_{LLS}$ вычисляют параметры описанного декартова бокса вокруг повернутого эллипса ошибок, выдавая честные СКО для экрана ТИС:
%[text] $\\sigma\_x=\\sqrt{K\_{LLS}(1,1)},\\quad\\sigma\_y=\\sqrt{K\_{LLS}(2,2)},\\quad\\sigma\_z=\\sqrt{K\_{LLS}(3,3)}$
%[text] 
%[text] ## 4. ФИЗИЧЕСКИЙ АНАЛИЗ ТРИГОНОМЕТРИЧЕСКОГО СЖАТИЯ (BIAS LLS) НА ТРАВЕРЗЕ
%[text] 
%[text] Рассмотрим критический случай, когда цель находится на траверзе центра измерительного креста ТИС ($X=0$) на огромном удалении ($Y=450$ км). Реперный пост расположен в начале координат ($x\_s=0,y\_s=0\\rightarrow b=0$).
%[text] 
%[text] Истинный геометрический азимут на север равен:
%[text] $\\alpha\_0=90^\\circ=\\frac{\\pi}{2}\\text{ рад}$
%[text] 
%[text] При наличии углового шума датчиков n измеренный азимут равен:
%[text] $\\alpha=90^\\circ+n$
%[text] 
%[text] Подставим зашумленный ракурс в первую азимутальную МНК-строку:
%[text] $\\sin(90^\\circ+n)\\cdot x-\\cos(90^\\circ+n)\\cdot y=0$
%[text] 
%[text] Используя строгие тригонометрические формулы приведения:
%[text] $\\sin(90^\\circ+n)=\\cos(n)$
%[text] $\\cos(90^\\circ+n)=-\\sin(n)$
%[text] 
%[text] Получаем линеаризованную строку связи для текущего зашумленного такта:
%[text] $\\cos(n)\\cdot x+\\sin(n)\\cdot y=0$
%[text] 
%[text] Отсюда выразим оценку дальности по оси OY, которую пытается найти линейный метод LLS:
%[text] $y=-x\\cdot\\frac{\\cos(n)}{\\sin(n)}=-x\\cdot\\cot(n)$
%[text] 
%[text] *ИНЖЕНЕРНЫЕ ВЫВОДЫ ИЗ АНАЛИЗА КОТАНГЕНСА:*
%[text] 
%[text] $\\langle|\\cot(n)|\\rangle\\approx\\frac{1}{0.0349}\\approx28.6$

