%[text] # 🔬 МАТЕМАТИЧЕСКИЙ ПАСПОРТ ЯДРА LLS: ПОЛНЫЙ АНАЛИТИЧЕСКИЙ ВЫВОД С НУЛЯ (lls_theory.txt)
%[text] Настоящий документ содержит исчерпывающее аналитическое описание и строгий, пошаговый вывод функциональных уравнений связи, структуры измерительной матрицы $H$ и вектора свободных членов $\mathbf{b}$ для безитерационного метода наименьших квадратов (LLS) пассивной триангуляции ТИС. Все выводы выполнены непосредственно из геометрических инвариантов правой декартовой системы координат ENU (East-North-Up) в рамках Эшелона А (Теоретический математический канон) — строго в системных единицах СИ (метры, радианы), без привлечения прикладных вычислических констант или весовых матриц Гаусса-Маркова.
%[text] 
%[text] ## 1. Геометрические инварианты измерительной задачи
%[text] ТИС осуществляет оценивание пространственного положения цели, находящейся в точке с истинными декартовыми координатами в локальной трехмерной прямоугольной системе ENU:
%[text] $\mathbf{X}=\[x,y,z\]^T \in \mathbb{R}^3$
%[text] 
%[text] Измерительная сеть состоит из $M$ наземных базовых постов с известными, статичными декартовыми координатами:
%[text] $\mathbf{X}\_{si}=\[x\_{si},y\_{si},z\_{si}\]^T,\quad i=1,\dots,M$
%[text] 
%[text] Для каждого поста ТИС вектор дальности (прямой визирный луч «пост $\rightarrow$ цель») задается пространственными приращениями в абсолютных метрах земли:
%[text] $\Delta x\_i = x - x\_{si}, \quad \Delta y\_i = y - y\_{si}, \quad \Delta z\_i = z - z\_{si}$
%[text] 
%[text] Продольная дальность до цели в горизонтальной проекции $XOY$ и полная пространственная дальность до $i$-го поста равны соответственно:
%[text] $r\_{xy,i}=\sqrt{\Delta x\_i^2+\Delta y\_i^2}, \quad r\_i = \Vert\mathbf{\Delta X}\_i\Vert = \sqrt{\Delta x\_i^2+\Delta y\_i^2+\Delta z\_i^2}$
%[text] 
%[text] Аппаратура каждого поста ТИС измеряет угловое направление на цель (вектор пеленгации) строго от инвариантной горизонтальной оси $OX$ декартовой земли против движения часовой стрелки в соответствии со строгим тригонометрическим законом:
%[text] 
%[text] * Азимут ($\alpha\_i$): угол в горизонтальной плоскости $XOY$ между осью $OX$ и проекцией визирного луча:
%[text] $\alpha\_i=\text{atan2}(\Delta y\_i,\Delta x\_i)\quad\rightarrow\quad\tan\alpha\_i=\frac{\Delta y\_i}{\Delta x\_i} = \frac{y-y\_{si}}{x-x\_{si}}$
%[text] 
%[text] * Угол места ($\beta\_i$): угол в вертикальной плоскости между плоскостью $XOY$ и пространственным визирным лучом:
%[text] $\beta\_i=\text{atan2}(\Delta z\_i,r\_{xy,i})\quad\rightarrow\quad\tan\beta\_i=\frac{\Delta z\_i}{r\_{xy,i}} = \frac{z-z\_{si}}{r\_{xy,i}}$
%[text] 
%[text] ## 2. Строгий аналитический вывод уравнений связи (Строки МНК)
%[text] Линейный безитерационный метод (LLS) требует точного преобразования нелинейных тригонометрических уравнений пеленгации к каноническому виду линейной системы нормальных уравнений:
%[text] $H \cdot \mathbf{X} = \mathbf{b}$
%[text] 
%[text] ## 2.1. Аналитический вывод строки горизонтального канала (Азимут $\alpha\_i$)
%[text] Из определения тангенса измеряемого азимута $\alpha\_i$ раскрываем тригонометрическую пропорцию:
%[text] $\tan\alpha\_i = \frac{\sin\alpha\_i}{\cos\alpha\_i} = \frac{y - y\_{si}}{x - x\_{si}}$
%[text] 
%[text] Раскрываем пропорцию крест-накрест, полностью избавляясь от нелинейного пространственного знаменателя в рамках единого расчетного контура:
%[text] $(x - x\_{si}) \cdot \sin\alpha\_i = (y - y\_{si}) \cdot \cos\alpha\_i$
%[text] 
%[text] $x \cdot \sin\alpha\_i - x\_{si} \cdot \sin\alpha\_i = y \cdot \cos\alpha\_i - y\_{si} \cdot \cos\alpha\_i$
%[text] 
%[text] Группируем неизвестные декартовы координаты цели $(x, y)$ в левой части уравнения, а известные координаты $i$-го поста ТИС переносим в правую часть:
%[text] $\sin\alpha\_i \cdot x - \cos\alpha\_i \cdot y = \sin\alpha\_i \cdot x\_{si} - \cos\alpha\_i \cdot y\_{si}$
%[text] 
%[text] Данное тождество определяет первую МНК-строку (азимутальную) линейного декартова оператора для $i$-го поста ТИС:
%[text] $H(2i-1, 1) = \sin\alpha\_i$
%[text] 
%[text] $H(2i-1, 2) = -\cos\alpha\_i$
%[text] 
%[text] $H(2i-1, 3) = 0$
%[text] 
%[text] $b(2i-1, 1) = \sin\alpha\_i \cdot x\_{si} - \cos\alpha\_i \cdot y\_{si}$
%[text] 
%[text] ## 2.2. Аналитический вывод строки вертикального канала (Угол места $\beta\_i$)
%[text] Из определения тангенса измеряемого угла места $\beta\_i$ раскрываем тригонометрическую пропорцию:
%[text] $\tan\beta\_i = \frac{\sin\beta\_i}{\cos\beta\_i} = \frac{\Delta z\_i}{r\_{xy,i}} \quad\rightarrow\quad \Delta z\_i \cdot \cos\beta\_i - r\_{xy,i} \cdot \sin\beta\_i = 0$
%[text] 
%[text] $(z - z\_{si}) \cdot \cos\beta\_i - r\_{xy,i} \cdot \sin\beta\_i = 0$
%[text] 
%[text] Продольная горизонтальная дальность $r\_{xy,i}$ нативно выражается через горизонтальные приращения и тригонометрические функции измерительного ракурса:
%[text] $r\_{xy,i} = \Delta x\_i \cdot \cos\alpha\_i + \Delta y\_i \cdot \sin\alpha\_i = (x - x\_{si}) \cdot \cos\alpha\_i + (y - y\_{si}) \cdot \sin\alpha\_i$
%[text] 
%[text] Подставляем полученное аналитическое выражение для $r\_{xy,i}$ в уравнение связи угла места:
%[text] $(z - z\_{si}) \cdot \cos\beta\_i - \left[ (x - x\_{si}) \cdot \cos\alpha\_i + (y - y\_{si}) \cdot \sin\alpha\_i \right] \cdot \sin\beta\_i = 0$
%[text] 
%[text] Раскрываем скобки и группируем слагаемые:
%[text] $z \cdot \cos\beta\_i - z_{si} \cdot \cos\beta\_i - x \cdot \cos\alpha\_i \sin\beta\_i + x_{si} \cdot \cos\alpha\_i \sin\beta\_i - y \cdot \sin\alpha\_i \sin\beta\_i + y_{si} \cdot \sin\alpha\_i \sin\beta\_i = 0$
%[text] 
%[text] Переносим неизвестные координаты цели $(x, y, z)$ в левую часть, строго выдерживая знаки правой тройки векторов ENU:
%[text] $-\cos\alpha\_i \sin\beta\_i \cdot x - \sin\alpha\_i \sin\beta\_i \cdot y + \cos\beta\_i \cdot z = -\cos\alpha\_i \sin\beta\_i \cdot x\_{si} - \sin\alpha\_i \sin\beta\_i \cdot y\_{si} + \cos\beta\_i \cdot z\_{si}$
%[text] 
%[text] Данное тождество определяет вторую МНК-строку (угломестную) линейного декартова оператора для $i$-го поста ТИС:
%[text] $H(2i, 1) = -\cos\alpha\_i \sin\beta\_i$
%[text] 
%[text] $H(2i, 2) = -\sin\alpha\_i \sin\beta\_i$
%[text] 
%[text] $H(2i, 3) = \cos\beta\_i$
%[text] 
%[text] $b(2i, 1) = -\cos\alpha\_i \sin\beta\_i \cdot x\_{si} - \sin\alpha\_i \sin\beta\_i \cdot y\_{si} + \cos\beta\_i \cdot z\_{si}$
%[text] 
%[text] ## 3. Алгебраический оператор безитерационного оценивания (Position)
%[text] В соответствии с требованиями Эшелона А, базовый измерительный контур оперирует исключительно равноточной системой сформированных линейных нормальных уравнений без весовых коэффициентов и без использования начального приближения:
%[text] $(H^T \cdot H) \cdot \mathbf{\lambda} = H^T \cdot \mathbf{b}$
%[text] 
%[text] Где матрица H имеет размер $[2M \times 3]$, а vector свободных членов b — размер $[2M \times 1]$. Прямой безитерационный расчет декартова вектора координат объекта $\mathbf{\lambda} = \[X; Y; Z\]^T$ (в метрах) выполняется в рамках единого расчетного контура методом обращения нормальной матрицы:
%[text] $\mathbf{\lambda} = (H^T \cdot H)^{-1} \cdot H^T \cdot \mathbf{b}$
%[text] 
%[text] Проверка численного вырождения измерительной геометрии на каждом этапе осуществляется строго по машинному нулю вещественной разрядной сетки вычислителя.
%[text] 
%[text] ## 4. ЭШЕЛОН Б. Имманентное котангенсное Bias-сжатие на траверзе
%[text] Данное каноническое линейное описание Слоя А содержит в себе скрытый, неустранимый геометрический порок, подлежащий фиксации на ЭТАПЕ I исследования:
%[text] 
%[text] * Рассмотрим критический случай, когда цель находится на траверзе центра измерительной базы ТИС ($x = 0$) на экстремальном удалении ($y = 450$ км). Реперный базовый пост расположен в начале координат плоскости ($x_{si} = 0, y_{si} = 0 \rightarrow b = 0$). Истинный азимут равен $\alpha\_0 = 90^{\circ} = \pi/2$ рад.
%[text] * При наличии случайного приборного шума угловых датчиков $n$, измеренный азимут равен $\alpha = 90^{\circ} + n$. Подставляя данный зашумленный ракурс в первую азимутальную строку связи Слоя А, получаем:
%[text] $\sin(90^{\circ} + n) \cdot x - \cos(90^{\circ} + n) \cdot y = 0$
%[text] * Используя строгие тригонометрические формулы приведения $\sin(90^{\circ} + n) = \cos(n)$ and $\cos(90^{\circ} + n) = -\sin(n)$, линеаризованная МНК-строка принимает вид:
%[text] $\cos(n) \cdot x + \sin(n) \cdot y = 0 \quad\rightarrow\quad y = -x \cdot \cot(n)$
%[text] * Поскольку приборный шум угловых датчиков ТИС $n$ центрирован и симметричен, математическое ожидание оценки дальности $y$ завязано на нелинейную функцию котангенса, которая при $n \rightarrow 0$ стремится к бесконечности несимметрично. Из-за нелинейного раскрыва котангенса случайное облако рассеяния линейного метода деформируется: оно катастрофически сжимается и смещается в сторону измерительной базы ТИС.
%[text] 
%[text] Это порождает мощнейшую систематическую ошибку оценивания (занижения дальности), которая делает невозможным точное определение координат на дальнем рубеже и физически не позволяет линейному методу пробить котангенсное сжатие без подключения честных нелинейных итераций.

