function [status, lambda] = lls3d_position(P, alpha, beta)
% =========================================================================
% ФУНКЦИЯ КЛАССИЧЕСКОГО НЕВЕСОВОГО ЛИНЕЙНОГО 3D-ПОЗИЦИОНИРОВАНИЯ (LLS)
% Входные параметры:
%   P      - Физическая матрица координат измерительных пунктов [3 x M]
%   alpha  - Вектор измеренных азимутов цели [M x 1] (радианы)
%   beta   - Вектор измеренных углов места цели [M x 1] (радианы)
% Выходные параметры:
%   status - Флаг выполнения (0 - успешно, 1 - сбой размерности, 2 - вырождение)
%   lambda - Оцененные декартовы координаты цели [x; y; z] (метры)
% =========================================================================
lambda = [NaN; NaN; NaN];
M = size(P, 2);

if M < 2
    status = 1; return;
end

H = zeros(2*M, 3);
b = zeros(2*M, 1);

for i = 1:M
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    
    % Строка азимута (от оси OX)
    H(2*i-1, 1) = sa;
    H(2*i-1, 2) = -ca;
    H(2*i-1, 3) = 0;
    b(2*i-1, 1) = sa*xs - ca*ys;
    
    % Строка угла места (от оси OX)
    H(2*i, 1) = -ca * sb;
    H(2*i, 2) = -sa * sb;
    H(2*i, 3) = cb;
    b(2*i, 1) = -ca*sb*xs - sa*sb*ys + cb*zs;
end

AtA = H.' * H;

% ЧЕСТНЫЙ АНАЛИТИЧЕСКИЙ ОТКАЗ: если определитель ушел в машинный ноль
if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
    status = 2; return; 
end

lambda = AtA \ (H.' * b);
status = 0;
end
