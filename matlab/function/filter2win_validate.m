function [ok,reason]=filter2win_validate(c)
% Complete configuration validation; invalid settings cannot change state.
if isstruct(c) && isscalar(c) && isfield(c,'schema_version') && isequal(c.schema_version,3)
    [ok,reason]=filter2win_validate_persistent(c); return;
end
ok=false; reason='INVALID_CONFIGURATION';
root={'schema_version','main','alt','flow','handover'};
if ~isstruct(c) || ~isscalar(c) || ~all(isfield(c,root)) || ...
        isfield(c,'rules') || ~number(c.schema_version,false) || c.schema_version~=2, return; end
names={'main','alt'};
for k=1:2
    w=c.(names{k});
    fields={'capacity','min_samples','min_span_seconds','history_seconds', ...
        'max_gap_seconds','freshness_seconds','model','known_velocity', ...
        'linear_min_pair_seconds','trim_fraction','band'};
    if ~isstruct(w) || ~isscalar(w) || ~all(isfield(w,fields)), return; end
    if ~integer(w.capacity,1) || ~integer(w.min_samples,2) || ...
            w.min_samples>w.capacity || ~nonnegative(w.min_span_seconds,false) || ...
            ~positive(w.history_seconds,true) || ~positive(w.max_gap_seconds,true) || ...
            ~nonnegative(w.freshness_seconds,true) || ...
            ~choice(w.model,{'constant','linear','known_velocity'}) || ...
            ~number(w.known_velocity,false) || ...
            ~nonnegative(w.linear_min_pair_seconds,false) || ...
            ~nonnegative(w.trim_fraction,false) || w.trim_fraction>=0.5
        return;
    end
    if strcmp(w.model,'linear') && w.min_samples<3, return; end
    b=w.band;
    fields={'lower_margin','upper_margin','exit_lower_margin','exit_upper_margin', ...
        'mad_multiplier','mad_floor','growth_per_second','max_mad', ...
        'max_abs_velocity','max_trimmed_range','max_adaptive_radius'};
    if ~isstruct(b) || ~isscalar(b) || ~all(isfield(b,fields)), return; end
    for j=1:7
        if ~nonnegative(b.(fields{j}),false), return; end
    end
    if ~nonnegative(b.max_mad,true) || ~nonnegative(b.max_abs_velocity,true) || ...
            ~nonnegative(b.max_trimmed_range,true) || ...
            ~nonnegative(b.max_adaptive_radius,true) || ...
            b.exit_lower_margin<b.lower_margin || b.exit_upper_margin<b.upper_margin
        return;
    end
end
a=c.alt;
fields={'confirm_seconds','allow_partial','partial_min_samples', ...
    'partial_min_span_seconds','partial_confirm_seconds','relative_mad_ratio', ...
    'on_reject','on_incompatible','gap_action','compatibility', ...
    'incompatible_min_samples','incompatible_min_seconds'};
if ~all(isfield(a,fields)) || ~nonnegative(a.confirm_seconds,false) || ...
        ~boolean(a.allow_partial) || ~integer(a.partial_min_samples,2) || ...
        a.partial_min_samples>a.capacity || ...
        ~nonnegative(a.partial_min_span_seconds,false) || ...
        ~nonnegative(a.partial_confirm_seconds,false) || ...
        ~positive(a.relative_mad_ratio,true) || ...
        ~choice(a.on_reject,{'retain','clear','restart'}) || ...
        ~choice(a.on_incompatible,{'restart','clear','ignore'}) || ...
        ~integer_or_inf(a.incompatible_min_samples,1) || ...
        ~nonnegative(a.incompatible_min_seconds,true) || ...
        ~choice(a.gap_action,{'restart','retain'})
    return;
end
if strcmp(a.model,'linear') && a.partial_min_samples<3, return; end
p=a.compatibility;
if ~isstruct(p) || ~isscalar(p) || ...
        ~all(isfield(p,{'method','neighbor_radius','neighbor_growth_per_second'})) || ...
        ~choice(p.method,{'median_band','nearest_neighbor','trimmed_range'}) || ...
        ~nonnegative(p.neighbor_radius,false) || ...
        ~nonnegative(p.neighbor_growth_per_second,false)
    return;
end
% A trimmed-range criterion needs an actual absolute bound; otherwise a
% drifting chain could pass only because its adaptive gate grew with it.
if strcmp(p.method,'trimmed_range') && ~isfinite(a.band.max_trimmed_range), return; end
f=c.flow;
fields={'outlier_hold_seconds','gap_hold_seconds','timeout_seconds','outlier_clock','gap_clock'};
if ~isstruct(f) || ~isscalar(f) || ~all(isfield(f,fields)) || ...
        ~nonnegative(f.outlier_hold_seconds,true) || ...
        ~nonnegative(f.gap_hold_seconds,true) || ~positive(f.timeout_seconds,true) || ...
        ~choice(f.outlier_clock,{'first_deviation','last_main_accept'}) || ...
        ~choice(f.gap_clock,{'last_input','last_main_accept'})
    return;
end
h=c.handover;
fields={'wait_seconds','duration_seconds','curve','cancel_on_main_return', ...
    'on_missing','settle_seconds','settle_min_samples'};
if ~isstruct(h) || ~isscalar(h) || ~all(isfield(h,fields)) || ...
        ~nonnegative(h.wait_seconds,false) || ~nonnegative(h.duration_seconds,false) || ...
        ~choice(h.curve,{'linear','smoothstep'}) || ~boolean(h.cancel_on_main_return) || ...
        ~choice(h.on_missing,{'pause','continue','cancel'}) || ...
        ~nonnegative(h.settle_seconds,false) || ~integer(h.settle_min_samples,0)
    return;
end
ok=true; reason='';
end

function ok=number(x,allow_inf)
ok=isa(x,'double') && isreal(x) && isscalar(x) && ...
    (isfinite(x) || (allow_inf && x==Inf));
end
function ok=nonnegative(x,allow_inf)
ok=number(x,allow_inf) && x>=0;
end
function ok=positive(x,allow_inf)
ok=number(x,allow_inf) && x>0;
end
function ok=integer(x,minimum)
ok=number(x,false) && x>=minimum && x==fix(x);
end
function ok=integer_or_inf(x,minimum)
ok=integer(x,minimum) || (number(x,true) && x==Inf);
end
function ok=boolean(x)
ok=(islogical(x) || isa(x,'double')) && isreal(x) && isscalar(x) && ismember(x,[0 1]);
end
function ok=choice(x,values)
ok=ischar(x) && isrow(x) && any(strcmp(x,values));
end
