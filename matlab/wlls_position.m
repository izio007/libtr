function [status, lambda] = wlls_position(P, alpha, beta, var_alpha, var_beta)
% =========================================================================
% CORE MATH KERNEL: WEIGHTED LINEAR LEAST SQUARES ESTIMATION (WLLS)
% SYSTEM MATRIX CONTEXT: DIMENSIONAL GAUSS-MARKOV WEIGHT MO DEL (1 / (sigma^2 * rho^2))
%
% PURPOSE: 
%   Взвешенный линейный МНК ТИС. Парирует аппаратную неравноточность 
%   измерительных каналов и геометрический масштаб промаха на местности 
%   на основе двухшагового расчета дальномерных плеч рычага.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат постов ТИС, размер [3 x M], метры.
%   alpha     - Вектор зашумленных азимутов цели, размер [M x 1], радианы.
%               Отсчет строго от положительного направления оси OX против часовой.
%   beta      - Вектор зашумленных углов места цели, размер [M x 1], радианы.
%               Отсчет строго от плоскости XOY вверх в диапазоне [-pi/2; pi/2].
%   var_alpha - Паспортный вектор дисперсий шума азимута постов, размер [M x 1], рад^2.
%   var_beta  - Паспортный вектор дисперсий шума угла места постов, размер [M x 1], рад^2.
%
% OUTPUT ARGUMENTS:
%   status - Код завершения операции (Выходной регистр Си-модуля):
%            0: Успешный расчет, ранг измерительной матрицы ТИС удержан.
%            1: Недостаточно информации для МНК (число активных постов M < 2).
%            2: Геометрическое вырождение, критическое падение ранга матрицы нормальных уравнений.
%   lambda - Рассчитанный декартов вектор координат [X; Y; Z], метры.
%            При status != 0 возвращает строго [NaN; NaN; NaN].
%
% COMPILER ARCHITECTURE REQUIREMENT (GCC / ANSI C99):
%   - Категорически исключить динамическую аллокацию ОЗУ (malloc). Matrix buffers строго double.
%   - Дальности до постов вычисляются от внутренней стартовой засечки lls_position.
%   - Все тригонометрические инварианты линеаризуются строго от оси OX.
% =========================================================================

lambda = [NaN; NaN; NaN];
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

% 2. ШАГ 1: ВНУТРЕННЕЕ ПРЕДЫСКАНИЕ КООРДИНАТ ЦЕЛИ ДЛЯ РАСЧЕТА ДАЛЬНОСТЕЙ
[st_lls, lambda_lls] = lls_position(P, alpha, beta);
if st_lls ~= 0
    status = st_lls; return;
end

H = zeros(2*M, 3);
b = zeros(2*M, 1);

x_init = lambda_lls(1); 
y_init = lambda_lls(2); 
z_init = lambda_lls(3);

% 3. ШАГ 2: СБОРКА РАЗМЕРНОЙ ВЕ СОВОЙ МАТРИЦЫ И НОРМАЛЬНЫХ УРАВНЕНИЙ (БАЗИС OX)
for i = 1:M
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    
    % Расчет расстояния от первой LLS-засечки до i-го поста ТИС
    rho_sq = (x_init - xs)^2 + (y_init - ys)^2 + (z_init - zs)^2;
    if rho_sq < 1e-3, rho_sq = 1e-3; end
    
    % Вычисление истинных размерных весов Гаусса-Маркова [1 / метры^2]
    w_a = 1.0 / sqrt(var_alpha(i) * rho_sq);
    w_b = 1.0 / sqrt(var_beta(i) * rho_sq);
    
    % Взвешенная строка азимута ТИС (от оси OX)
    H(2*i-1, 1) = w_a * sa;
    H(2*i-1, 2) = w_a * (-ca);
    H(2*i-1, 3) = 0;
    b(2*i-1, 1) = w_a * (sa*xs - ca*ys);
    
    % Взвешенная строка угла места ТИС (ИСТИННЫЙ ВЕРИФИЦИРОВАННЫЙ ЗНАК ТИС)
    H(2*i, 1) = w_b * (-ca * sb);
    H(2*i, 2) = w_b * (-sa * sb);
    H(2*i, 3) = w_b * cb;
    b(2*i, 1) = w_b * (-ca*sb*xs - sa*sb*ys + cb*zs);
end

AtA = H.' * H;

% 4. АБСОЛЮТНАЯ АНАЛИТИЧЕСКАЯ ЧЕСТНОСТЬ ПО МАШИННОМУ НУЛЮ EPS
if rcond(AtA) < 2.2204e-16 || isnan(rcond(AtA))
    status = 2; return;
end

% 5. РАСЧЕТ И ИЗВЛЕЧЕНИЕ КООРДИНАТ ЦЕЛИ WLLS
lambda = AtA \ (H.' * b);
status = 0;
end
