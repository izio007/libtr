function [status, lambda] = wlls_position(P, alpha, beta, var_alpha, var_beta)
% =========================================================================
% CORE MATH KERNEL: WEIGHTED LINEAR LEAST SQUARES ESTIMATION (WLLS)
% SYSTEM MATRIX CONTEXT: DIMENSIONAL GAUSS-MARKOV WEIGHT MODEL (1 / (sigma * rho))
%
% PURPOSE: 
%   Взвешенный линейный безитерационный метод наименьших квадратов ТИС. 
%   Парирует аппаратную неравноточность измерительных каналов постов 
%   и нелинейный геометрический масштаб промаха на местности на основе 
%   двухшагового расчета дальномерных плеч рычага. 
%   Оперирует строго в абсолютных метрах и радианах СИ.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат базовых постов ТИС, размер [3 x M], метры.
%               Строки соответствуют осям [x_si; y_si; z_si] в локальной СК ENU.
%   alpha     - Вектор зашумленных азимутов цели, размер [M x 1], радианы.
%               Отсчет строго от положительного направления оси OX против часовой.
%   beta      - Вектор зашумленных углов места цели, размер [M x 1], радианы.
%               Отсчет строго от плоскости XOY вверх в диапазоне [-pi/2; pi/2].
%   var_alpha - Вектор дисперсий шума азимута постов, размер [M x 1], рад^2.
%   var_beta  - Вектор дисперсий шума угла места постов, размер [M x 1], рад^2.
%
% OUTPUT ARGUMENTS:
%   status    - Код завершения операции (Выходной аналитический признак):
%               0: Успешный расчет, ранг взвешенной нормальной матрицы удержан.
%               1: Недостаточно информации для МНК (число активных постов M < 2).
%               2: Геометрическое вырождение, критическое падение ранга матрицы нормальных уравнений.
%   lambda    - Рассчитанный декартов вектор координат [X; Y; Z], метры.
%               При status != 0 возвращает строго [NaN; NaN; NaN].
%
% COMPILER ARCHITECTURE REQUIREMENT (ANSI C99 COMPLIANCE):
%   - Исключить динамическое выделение памяти в процессе вычислений. 
%   - Опорные плечи дальностей до постов вычисляются от внутренней стартовой засечки lls_position.
%   - Все тригонометрические инварианты линеаризуются строго от инвариантной оси OX.
%   - Проверка обусловленности выполняется по машинному нулю без регуляризаций.
% =========================================================================

lambda = [NaN; NaN; NaN];
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

% 2. ШАГ 1: ВНУТРЕННЕЕ ПРЕДЫСКАНИЕ КООРДИНАТ ЦЕЛИ ДЛЯ ВЫЧИСЛЕНИЯ ОПОРНЫХ ПЛЕЧ
[st_lls, lambda_lls] = lls_position(P, alpha, beta);
if st_lls ~= 0
    status = st_lls; return;
end

H_w = zeros(2 * M, 3);
b_w = zeros(2 * M, 1);

x_init = lambda_lls(1); 
y_init = lambda_lls(2); 
z_init = lambda_lls(3);

% 3. ШАГ 2: СБОРКА РАЗМЕРНОЙ ИЗМЕРИТЕЛЬНОЙ МАТРИЦЫ И ВЗВЕШЕННЫХ УРАВНЕНИЙ СВЯЗИ
for i = 1:M
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    sa = sin(alpha(i)); ca = cos(alpha(i));
    sb = sin(beta(i));  cb = cos(beta(i));
    
    % Вычисление опорного плеча дальности от предварительной засечки LLS до i-го поста
    rho_sq = (x_init - xs)^2 + (y_init - ys)^2 + (z_init - zs)^2;
    if rho_sq < 1e-3, rho_sq = 1e-3; end
    rho = sqrt(rho_sq);
    
    % Расчет размерных весовых коэффициентов Гаусса-Маркова [1 / метр]
    w_a = 1.0 / (sqrt(var_alpha(i)) * rho);
    w_b = 1.0 / (sqrt(var_beta(i)) * rho);
    
    % Взвешенная МНК-строка горизонтального канала (Азимут alpha_i)
    H_w(2*i-1, 1) = w_a * sa;
    H_w(2*i-1, 2) = w_a * (-ca);
    H_w(2*i-1, 3) = 0;
    b_w(2*i-1, 1) = w_a * (sa * xs - ca * ys);
    
    % Взвешенная МНК-строка вертикального канала (Угол места beta_i)
    H_w(2*i, 1) = w_b * (-ca * sb);
    H_w(2*i, 2) = w_b * (-sa * sb);
    H_w(2*i, 3) = w_b * cb;
    b_w(2*i, 1) = w_b * (-ca * sb * xs - sa * sb * ys + cb * zs);
end

AtA_w = H_w.' * H_w;

% 4. АБСОЛЮТНАЯ АНАЛИТИЧЕСКАЯ ЧЕСТНОСТЬ ПО МАШИННОМУ НУЛЮ ВЕЩЕСТВЕННОЙ СЕТКИ
if rcond(AtA_w) < 2.2204e-16 || isnan(rcond(AtA_w))
    status = 2; return; % Честный аналитический отмах при потере ранга жесткости
end

% 5. ВЫЧИСЛЕНИЕ ФИНАЛЬНОГО ВЕКТОРА КООРДИНАТ WLLS В РАМКАХ ЕДИНОГО МАТЕМАТИЧЕСКОГО ОПЕРАТОРА
lambda = AtA_w \ (H_w.' * b_w);
status = 0;
end
