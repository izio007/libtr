function valid = test_result_valid_mask(r)
% Validate persisted engine results; never infer missing historical validity.
id='libtr:result:Validity';
assert(isstruct(r) && isscalar(r) && ...
    all(isfield(r,{'samples','statuses','metrics','valid','contract_violations'})),id, ...
    'Result requires samples, statuses, metrics and explicit validity');
assert(isnumeric(r.samples) && isreal(r.samples) && ismatrix(r.samples) && ...
    size(r.samples,1)>0,id,'Invalid samples');
assert(isnumeric(r.statuses) && isreal(r.statuses) && ...
    all(isnan(r.statuses(:)) | ismember(r.statuses(:),[0 1 2])), ...
    id,'Invalid statuses');
assert(isstruct(r.metrics) && isscalar(r.metrics) && ...
    isfield(r.metrics,'successful'),id,'Missing result count');
N=size(r.samples,2);
assert(islogical(r.valid) && isequal(size(r.valid),[1 N]) && ...
    islogical(r.contract_violations) && isequal(size(r.contract_violations),[1 N]) && ...
    isequal(size(r.statuses),[1 N]),id,'Invalid result mask shape or type');
valid=r.valid;
consistent=(r.statuses==0 & all(isfinite(r.samples),1)) | ...
    (ismember(r.statuses,[1 2]) & all(isnan(r.samples),1));
assert(all(consistent | r.contract_violations),id, ...
    'Unmarked output contract violation');
assert(isequal(valid,r.statuses==0 & all(isfinite(r.samples),1) & ~r.contract_violations), ...
    id,'Result mask disagrees with samples or status');
assert(isnumeric(r.metrics.successful) && isreal(r.metrics.successful) && ...
    isscalar(r.metrics.successful) && r.metrics.successful==sum(valid), ...
    id,'Result count disagrees with mask');
end