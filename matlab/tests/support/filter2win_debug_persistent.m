function text=filter2win_debug_persistent(d)
% Phase shows an ongoing blend even when the current status describes waiting.
names={'-','A','B'};
text=sprintf(['[TACT %04d] s3 t=%.9g x=%.9g -> y=%.9g valid=%d' ...
    ' | active=%s->%s route=%s accepted=%d' ...
    ' | phase=%s->%s action=%s' ...
    ' | status=%d(%s) event=%s reason=%s' ...
    ' | A=%d->%d B=%d->%d blend_weight=%.9g'], ...
    d.tact,d.time,d.measurement,d.output,d.valid, ...
    names{d.active_before+1},names{d.active_window+1},names{d.route+1},d.accepted, ...
    d.phase_before,d.phase,d.action,d.status,d.status_name,d.event,d.reason, ...
    d.main_before,d.main_count,d.alt_before,d.alt_count,d.blend_weight);
end
