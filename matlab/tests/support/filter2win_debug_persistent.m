function text=filter2win_debug_persistent(d)
% Rendering of actual kernel decisions, with data and thresholds.
g=d.guards; p=g.proposal;
text=sprintf(['[TACT %04d] Time: %.9g s | Status: %d (%s) | Meas: %.9g | Valid: %d | Output: %.9g\n' ...
    '         >> A/B active: %d -> %d | Route: %d | Accepted: %d | Reason: %s\n' ...
    '         >> Rule: %s | Event: %s | A: %d -> %d | B: %d -> %d\n' ...
    '         >> Normalized distance A/B: %.9g / %.9g | Output age: %.9g s\n' ...
    '         >> Proposed n=%d, span=%.9g s, MAD=%.9g, range=%.9g | Ready=%d\n' ...
    '         >> New-point residual: %.9g | Removal threshold: %.9g\n' ...
    '         >> Removed old timestamps: %s | FIFO evicted timestamp: %s | Blend: %.9g\n'], ...
    d.tact,d.time,d.status,d.status_name,d.measurement,d.valid,d.output, ...
    d.active_before,d.active_window,d.route,d.accepted,d.reason,d.rule,d.event, ...
    d.main_before,d.main_count,d.alt_before,d.alt_count,g.distance(1),g.distance(2),g.age, ...
    p.stats.count,p.stats.span,p.stats.model.mad,p.stats.range,p.stats.ready, ...
    p.new_residual,p.threshold,mat2str(d.removed.time),mat2str(d.evicted.time),d.blend_weight);
text=[text sprintf('         >> Hold limit: %.9g s | Age <= limit: %d\n',g.hold_limit,g.age<=g.hold_limit)];
if d.route>0
    w=g.window_config;
    text=[text sprintf(['         >> Required n >= %d, span >= %.9g s; MAD <= %.9g, range <= %.9g, |velocity| <= %.9g\n' ...
        '         >> Gate prediction: %.9g | Lower/upper margins: %.9g / %.9g\n'], ...
        w.min_samples,w.min_span_seconds,w.band.max_mad,w.band.max_range,w.band.max_abs_velocity, ...
        g.prediction(d.route),g.lower(d.route),g.upper(d.route))];
end
for k=1:numel(d.blocked_rules)
    r=d.blocked_rules{k};
    text=[text sprintf('         >> Pending %s: n=%d/%d, time=%.9g/%.9g s, dwell=%.9g/%.9g s\n', ...
        r.name,r.hits,r.required_hits,r.seconds,r.required_seconds,r.dwell,r.required_dwell)]; %#ok<AGROW>
end
for k=1:numel(d.rule_checks)
    r=d.rule_checks(k);
    text=[text sprintf('         >> %s: %.9g %s %.9g -> %d\n',r.metric,r.actual,r.operator,r.threshold,r.passed)]; %#ok<AGROW>
end
end
