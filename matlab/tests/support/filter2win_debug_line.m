function text=filter2win_debug_line(d)
% Read-only formatter: all values originate in this step's diagnostic record.
if d.api_status~=0
    text=sprintf('[REFUSED] Reason: %s | Numerical state unchanged.\n',d.reason);
    return;
end
g=d.guards;
text=sprintf(['[TACT %04d] Time: %.9g s | Status: %d (%s) | Meas: %.9g' ...
    ' | Valid: %d | Output: %.9g\n' ...
    '         >> Transition: %d -> %d | Rule: %s | Event: %s\n' ...
    '         >> Reason: %s | Main: %d -> %d | Alt: %d -> %d\n' ...
    '         >> Main prediction: %.9g | Residual: %.9g | Entry: [-%.9g,+%.9g]' ...
    ' | Exit: [-%.9g,+%.9g]\n' ...
    '         >> Alt: n=%d, span=%.9g s, confirmed=%.9g s, max_gap=%.9g s, age=%.9g s\n' ...
    '         >> Required: n>=%d, span>=%.9g s, confirmed>=%.9g s, max_gap<=%.9g s, age<=%.9g s\n' ...
    '         >> Main before step: level=%.9g, velocity=%.9g, MAD(raw)=%.9g\n' ...
    '         >> Main candidate: level=%.9g, velocity=%.9g, MAD(raw)=%.9g\n' ...
    '         >> Alt model: level=%.9g, velocity=%.9g, MAD(raw)=%.9g | MAD_limit=%.9g\n' ...
    '         >> Trimmed range: %.9g <= %.9g | Tail-trimmed sample count: %d\n' ...
    '         >> Compatibility method: %s | Neighbor distance=%.9g, limit=%.9g\n' ...
    '         >> Incompatible action: %s | Streak n=%d/%g, age=%.9g/%.9g s\n' ...
    '         >> Compatible: %d | Alt quality: %d | Target quality: %d | Relative quality: %d | Ready: %d | Partial: %d\n' ...
    '         >> Settling: age=%.9g/%.9g s, real new samples=%d/%d, pending=%d\n' ...
    '         >> Idle=%.9g s | Gap age=%.9g s | Outlier age=%.9g s | Blend weight=%.9g\n'], ...
    d.tact,d.time,d.status,d.status_name,d.measurement,d.valid,d.output, ...
    d.previous_status,d.status,d.rule,d.event,d.reason, ...
    d.main_before,d.main_count,d.alt_before,d.alt_count, ...
    g.prediction,g.residual,g.enter_lower,g.enter_upper,g.exit_lower,g.exit_upper, ...
    g.alt_metrics.count,g.alt_metrics.span,g.alt_confirmation, ...
    g.alt_metrics.max_gap,g.alt_metrics.age, ...
    g.limits.alt_min_samples,g.limits.alt_min_span,g.limits.alt_confirm_seconds, ...
    g.limits.alt_max_gap,g.limits.alt_freshness, ...
    g.primary_model.level,g.primary_model.velocity,g.primary_model.mad, ...
    g.main_model.level,g.main_model.velocity,g.main_model.mad, ...
    g.candidate_model.level,g.candidate_model.velocity,g.candidate_model.mad, ...
    g.limits.alt_max_mad,g.candidate_model.trimmed_range,g.limits.alt_max_trimmed_range, ...
    g.candidate_model.trimmed_count,g.limits.compatibility,g.neighbor_distance,g.neighbor_limit, ...
    g.incompatible_action,g.incompatible_samples,g.limits.incompatible_min_samples, ...
    g.incompatible_age,g.limits.incompatible_min_seconds, ...
    ~g.incompatible,g.alt_quality,g.target_quality,g.relative_quality,g.alt_ready,g.partial, ...
    g.settle_age,g.limits.settle_seconds,g.settle_samples,g.limits.settle_min_samples, ...
    g.settle_pending,g.idle,g.gap_age,g.outlier_age,d.blend_weight);
for k=1:numel(d.blocked_rules)
    r=d.blocked_rules{k};
    text=[text sprintf(['         >> Pending rule %s: hits %d/%d; confirmation %.9g/%.9g s;' ...
        ' state dwell %.9g/%.9g s\n'],r.name,r.hits,r.required_hits, ...
        r.seconds,r.required_seconds,r.dwell,r.required_dwell)]; %#ok<AGROW>
    text=[text render_checks(r.checks)]; %#ok<AGROW>
end
text=[text render_checks(d.rule_checks)];
end

function text=render_checks(checks)
text='';
for k=1:numel(checks)
    c=checks(k);
    text=[text sprintf('         >> Guard: %s %.9g %s %.9g -> %d\n', ...
        c.metric,c.actual,c.operator,c.threshold,c.passed)]; %#ok<AGROW>
end
end
