function text=filter2win_debug_line(d)
% One line from the actual diagnostic record; no policy is recomputed here.
if d.api_status~=0
    text=sprintf('[REFUSED] reason=%s | Numerical state unchanged.',d.reason);
    return;
end
if isfield(d,'schema_version') && d.schema_version==3
    text=filter2win_debug_persistent(d); return;
end
text=sprintf(['[TACT %04d] s2 t=%.9g x=%.9g -> y=%.9g valid=%d' ...
    ' | status=%d->%d(%s) event=%s reason=%s' ...
    ' | main=%d->%d alt=%d->%d blend_weight=%.9g'], ...
    d.tact,d.time,d.measurement,d.output,d.valid, ...
    d.previous_status,d.status,d.status_name,d.event,d.reason, ...
    d.main_before,d.main_count,d.alt_before,d.alt_count,d.blend_weight);
end
