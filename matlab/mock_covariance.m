function [status, K_cart, V_axes, S_eigen] = mock_covariance(P, alpha, beta, var_alpha, var_beta, lambda)
% =========================================================================
% TIS IMITATION KERNEL: DE CARTESIAN EXACT CRER BOUND REPER OPERATOR (MOCK)
% SYSTEM MATRIX CONTEXT: Fisher INFORMATION MATRIX WITH EIGENVALUE DECOMPOSITION
%
% PURPOSE:
%   Расчет полной декартовой ковариационной матрицы погрешностей предела Рао-Крамера 
%   на основе аддитивной сборки информационной матрицы Фишера. Выполняет 
%   спектральное разложение симметричного тензора для фиксации пространственной 
%   ориентации и длин главных полуосей рассеяния.
%
% INPUT ARGUMENTS:
%   P         - Матрица координат измерительных постов ТИС, размер [3 x M], метры.
%               Строки соответствуют декартовым осям [x_si; y_si; z_si] в локальной СК ENU.
%   alpha     - Вектор идеальных азимутов цели, размер [M x 1], радианы.
%   beta      - Вектор идеальных углов места цели, размер [M x 1], радианы.
%   var_alpha - Вектор дисперсий приборного шума каналов азимута датчиков, размер [M x 1], рад^2.
%   var_beta  - Вектор дисперсий приборного шума каналов угла места датчиков, размер [M x 1], рад^2.
%   lambda    - Вектор истинных декартовых координат репера цели [X_true; Y_true; Z_true], метры.
%
% OUTPUT ARGUMENTS:
%   status    - Код завершения вычислительной операции (Выходной аналитический признак):
%               0: Успешный расчет, информационная матрица Фишера удержан и обратима.
%               1: Недостаточно информации для МНК (число активных постов измерительной сети M < 2).
%               2: Численное вырождение, критическое падение ранга матрицы нормальных уравнений.
%   K_cart    - Полная декартова ковариационная матрица погрешностей предела Рао-Крамера, 
%               размер [3 x 3], ед. изм.: метры^2.
%   V_axes    - Ортогональная матрица направляющих косинусов главных осей эллипсоида, размер [3 x 3].
%               Столбцы задают пространственные собственные векторы рассеяния относительно СК ENU.
%   S_eigen   - Диагональная матрица собственных значений тензора ковариации, размер [3 x 3],
%               элементы которой определяют квадраты истинных главных полуосей рассеяния (м^2).
%
% COMPILER ARCHITECTURE REQUIREMENT (ANSI C99 COMPLIANCE):
%   - Исключить динамическое выделение памяти в процессе вычислений.
%   - Частные производные градиентов берутся строго в точке истинного репера цели lambda.
%   - Проверка обусловленности выполняется по машинному нулю вещественной разрядной сетки.
% =========================================================================

K_cart = NaN(3, 3);
V_axes = NaN(3, 3);
S_eigen = NaN(3, 3);
M = size(P, 2);

% 1. ПРОВЕРКА РАНГА ИЗБЫТОЧНОСТИ ИЗМЕРИТЕЛЬНОЙ СЕТИ ТИС
if M < 2
    status = 1; return;
end

x_true = lambda(1); 
y_true = lambda(2); 
z_true = lambda(3);

I_F_cart = zeros(3, 3);

% 2. АДДИТИВНАЯ СБОРКА ДЕКАРТОВОЙ МАТРИЦЫ ФИШЕРА ПО ГРАДИЕНТАМ РЕПЕРА
for i = 1:M
    xs = P(1, i); ys = P(2, i); zs = P(3, i);
    
    % Пространственные приращения относительно i-го наземного поста ТИС
    dx_i = x_true - xs;
    dy_i = y_true - ys;
    dz_i = z_true - zs;
    
    r_xy_i_sq = dx_i^2 + dy_i^2;
    r_xy_i = sqrt(r_xy_i_sq);
    if r_xy_i < 1e-3, r_xy_i = 1e-3; r_xy_i_sq = 1e-6; end
    
    % [ХИРУРГИЧЕСКОЕ ИСПРАВЛЕНИЕ ОПЕЧАТКИ СЛОЯ Б]: Синхронизация радиус-инварианта полной дальности
    r_i_sq = r_xy_i_sq + dz_i^2; 
    r_i = sqrt(r_i_sq);
    if r_i < 1e-3, r_i = 1e-3; r_i_sq = 1e-6; end
    
    % Вектор частных декартовых производных азимутального канала i-го поста
    grad_alpha = [ -dy_i / r_xy_i_sq; ...
                    dx_i / r_xy_i_sq; ...
                    0 ];
                
    % Вектор частных декартовых производных угломестного канала i-го поста
    grad_beta = [ -(dx_i * dz_i) / (r_i_sq * r_xy_i); ...
                  -(dy_i * dz_i) / (r_i_sq * r_xy_i); ...
                    r_xy_i / r_i_sq ];
                
    % Кумулятивное взвешенное суммирование математических ожиданий градиентов
    I_F_cart = I_F_cart + (1.0 / var_alpha(i)) * (grad_alpha * grad_alpha.') + ...
                          (1.0 / var_beta(i))  * (grad_beta * grad_beta.');
end

% 3. КРИТИЧЕСКИЙ КОНТРОЛЬ ПОЛОЖЕНИЯ РАНГА ПО МАШИННОМУ НУЛЮ ВЕЩЕСТВЕННОЙ СЕТКИ
if rcond(I_F_cart) < 2.2204e-16 || isnan(rcond(I_F_cart))
    status = 2; return;
end

% 4. ПРЯМОЕ ИНВЕРТИРОВАНИЕ ДЕКАРТОВОЙ ИНФОРМАЦИОННОЙ МАТРИЦЫ ФИШЕРА
K_cart = inv(I_F_cart);

% 5. АНАЛИТИЧЕСКИЙ ОПЕРАТОР СПЕКТРАЛЬНОГО РАЗЛОЖЕНИЯ ТЕНЗОРА КОВАРИАЦИИ
[V_axes, S_eigen] = eig(K_cart);
status = 0;
end
