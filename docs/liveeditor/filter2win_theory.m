%[text] ## Анализ хронологии теста:
%[text] 
%[text] - Интервал 0–60 с: Процесс стабилен. Одиночный выброс на 30-й секунде отфильтрован в $W_{\text{main}}$ ($P = 0.05 \le 0.25$), геометрия ведения не нарушена.
%[text] - Интервал 60–100 с: Вход в зону многолучевости. Отметки сыпятся в точке $X=25$ м. На 60-й секунде активируется $W_{\text{alt}}$. На 72-й секунде ($M=5$) алгоритм классифицирует устойчивую систематическую ошибку. Основная траектория переходит на «слепое ведение» по прогнозу ($X=10$ м). Ложные координаты изолированы.
%[text] - Интервал 100–170 с: Вход в мертвую зону, данные не поступают. На 170-й секунде срабатывает временной критерий деградации ($170 - 100 = 70$ с). Альтернативное окно сбрасывается в ноль ($W_{\text{alt}} = \emptyset$). Память очищена от ложного тренда. Основной прогноз продолжает удерживать истинную координату.
%[text] - Интервал 200–300 с: Выход из мертвой зоны. Первая же отметка приходит в точку $X=10.2$ м. Расстояние до основного прогноза $0.2 \le R_{\text{max}}$. Система мгновенно переходит в режим штатной коррекции по реальному сигналу. \

