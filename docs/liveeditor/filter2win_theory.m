%[text] ## Математическая модель двухоконного фильтра координатных аномалий в связанной системе координат
%[text] Настоящая работа посвящена повышению устойчивости фильтрации траекторных измерений, поступающих с фиксированным временным шагом $\Delta t = 3$ с в связанной системе координат (ССК). Алгоритм устраняет грубые одиночные выбросы и компенсирует длительные систематические ошибки пеленгации без потери непрерывности сопровождения.
%[text] ------------------------------
%[text] ## 1. Математическое описание алгоритма
%[text] Пусть $\mathbf{X}\_i = \[x\_i, y\_i, z\_i\]^T \\in \\mathbb{R}^3$ — вектор координат объекта на шаге $i$.
%[text] Система оперирует двумя скользящими множествами (окнами) бинарных признаков:
%[text] 
%[text] - $W\_{\\text{main}}$ — основное окно долговременной стабильности, мощность $\\vert{}W\_{\\text{main}}\\vert{} = N = 20$.
%[text] - $W\_{\\text{alt}}$ — альтернативное окно локальной кучности, мощность $\\vert{}W\_{\\text{alt}}\\vert{} = M = 5$. \
%[text] 
%[text] ## Блок А. Первичный метрический контроль и экстраполяция
%[text] Для каждого шага определяется вектор динамической нормы (прогноз) $\mathbf{X}\_{\\text{norm}, i}$:
%[text] $\\mathbf{X}\_{\\text{norm}, i} = \\mathbf{X}\_{\\text{last\_valid}} + \\mathbf{V}\_i \\cdot \\Delta t$
%[text] где $\mathbf{X}\_{\\text{last\_valid}}$ — последний подтвержденный вектор нормы, $\mathbf{V}\_i$ — вектор расчетной скорости в ССК.
%[text] Вычисляется евклидово расстояние (метрика отклонения):
%[text] $R\_{\\text{main}, i} = \\Vert\\mathbf{X}\_i - \\mathbf{X}\_{\\text{norm}, i}\\Vert$
%[text] Формируется бинарный признак аномальности $e\_i$:
%[text] $e\_i = \\begin{cases} 0, & \\text{если } R\_{\\text{main}, i} \\le R\_{\\text{max}} \\ 1, & \\text{если } R\_{\\text{main}, i} \> R\_{\\text{max}} \\end{cases}$
%[text] где $R\_{\\text{max}}$ — жесткий физический допуск на линейное перемещение объекта за интервал $\Delta t$.
%[text] 
%[text] ## Блок Б. Непрерывный анализ и управление окнами
%[text] Элемент $e\_i$ поступает в $W\_{\\text{main}}$ со сдвигом выборки. Вычисляется текущая доля аномалий:
%[text] $P\_i = \\frac{1}{N} \\sum\_{j \\in W\_{\\text{main}}} e\_j$
%[text] 1. Режим «Норма» ($P\_i \\le 0.25$): Вектор $\mathbf{X}\_i$ признается истинным. Назначается $\mathbf{X}\_{\\text{last\_valid}} = \mathbf{X}\_i$. Окно $W\_{\\text{alt}}$ принудительно очищается ($W\_{\\text{alt}} = \\emptyset$).
%[text] 2. Режим «Слепое ведение» ($P\_i \> 0.25$): Координата $\mathbf{X}\_i$ блокируется и не участвует в уточнении траектории. Коррекция ССК прекращается, система переходит на чисто математический прогноз по вектору скорости. Параллельно точка $\mathbf{X}\_i$ направляется в $W\_{\\text{alt}}$. \
%[text] 
%[text] ## Блок В. Логика альтернативного окна и критерии сброса
%[text] Внутри $W\_{\\text{alt}}$ вычисляется локальное расстояние между текущей и предыдущей аномальными точками: $R\_{\\text{alt}, i} = \\Vert\\mathbf{X}\_i - \\mathbf{X}\_{\\text{alt}, i-1}\\Vert$.
%[text] 
%[text] - Если $R\_{\\text{alt}, i} \\le R\_{\\text{max}}$, то $W\_{\\text{alt}}$ заполняется. При достижении мощности $\\vert{}W\_{\\text{alt}}\\vert{} = 5$ и подтверждении маневра внешними критериями происходит мгновенная переинициализация: $W\_{\\text{main}} = \\emptyset$, а текущий центроид $W\_{\\text{alt}}$ становится новой базовой нормой.
%[text] - Условие временной деградации (Таймаут): Если на протяжении критического интервала $\Delta T_{\text{max}} = 70$ с в окно $W_{\text{alt}}$ не поступает новых элементов ($t_{\text{current}} - t_{\text{last\_alt\_mark}} > \Delta T_{\text{max}}$), альтернативная траектория признается ложной. Окно аннулируется: $W_{\text{alt}} = \emptyset$. Основная система остается в режиме экстраполяции. \
%[text] ------------------------------
%[text] ## 2. Область применения алгоритма
%[text] Метод разработан для парирования трех критических типов деструктивных воздействий на координатную выборку:
%[text] 
%[text] 1. Одиночные импульсные помехи (выбросы): Кратковременные сбои измерительного тракта (1–2 отсчета). Алгоритм изолирует их с помощью бинарного признака $e\_i = 1$, исключая искажение скользящего центроида траектории.
%[text] 2. Длительные систематические ошибки пеленгации (многолучевость): Заход объекта в сектор отражений или интерференции, где ложные отметки стабильно идут со смещением в течение длительного времени (до 60–70 с). Алгоритм переводит основную траекторию в режим прогноза, локализуя ложный пучок в альтернативном окне.
%[text] 3. Полная потеря измерительного сигнала (мертвая зона): Прекращение поступления любых координат при выходе из строя или экранировании пеленгатора. Посредством временного таймаута в 70 с алгоритм своевременно очищает буфер аномалий, предотвращая забивание памяти устаревшим шумом, и сохраняет готовность к мгновенному перезахвату цели при ее выходе из мертвой зоны. \
%[text] ------------------------------
%[text] ## 3. Комплексный тест и визуализация результатов
%[text] Ниже представлены результаты имитационного моделирования процесса (100 отсчетов, $T=300$ с, допуск $R_{\text{max}} = 0.5$ м). В середине эксперимента смоделирован длительный уход пеленга на величину $+15$ м (вход в сектор многолучевости на 60-й секунде) с последующим полным пропаданием сигнала на 100-й секунде (вход в мертвую зону).
%[text] 
if exist('length', 'var'), clear('length'); end
t_axes = 0:3:300;
X_true_vector = 10 * ones(size(t_axes)); 
X_meas_vector = X_true_vector;
X_meas_vector(t_axes >= 60 & t_axes <= 100) = 25; 
idx_drop_mask = t_axes > 100 & t_axes < 170; 
t_valid_axes = t_axes(~idx_drop_mask); 
X_meas_valid_vector = X_meas_vector(~idx_drop_mask);

subplot(2,1,1);
plot(t_axes, X_true_vector, 'k-', 'LineWidth', 2); hold on;
plot(t_valid_axes(X_meas_valid_vector==10), X_meas_valid_vector(X_meas_valid_vector==10), 'g.', 'MarkerSize', 12);
plot(t_valid_axes(X_meas_valid_vector==25), X_meas_valid_vector(X_meas_valid_vector==25), 'r.', 'MarkerSize', 12);
stairs(t_axes(t_axes>=100 & t_axes<=170), 10*ones(1,sum(idx_drop_mask)), 'b--', 'LineWidth', 1.5);
grid on; title('РИСУНОК 1. ТРАЕКТОРИЯ ИСТИННОГО ДВИЖЕНИЯ И ВХОДЯЩИЕ ОТМЕТКИ В ССК');
xlabel('Время t, с'); ylabel('Координата X, м');
legend('Истинный курс', 'Валидные отметки', 'Систематическая ошибка', 'Экстраполяция (прогноз)', 'Location', 'Best');

subplot(2,1,2);
t_alt_axes = 0:3:300;
W_alt_val_vector = zeros(size(t_alt_axes));
W_alt_val_vector(t_alt_axes >= 60 & t_alt_axes <= 72) = 0:4;
W_alt_val_vector(t_alt_axes > 72 & t_alt_axes < 170) = 5;
W_alt_val_vector(t_alt_axes >= 170) = 0;
plot(t_alt_axes, W_alt_val_vector, 'b-', 'LineWidth', 2); hold on;
plot(100, 5, 'ro', 'MarkerSize', 8, 'LineWidth', 2);
text(105, 4.5, '\leftarrow Сигнал пропал', 'Color', 'r');
text(175, 0.5, '\leftarrow Сброс W_{alt} (Таймаут)', 'Color', 'b');
grid on; title('РИСУНОК 2. ДИНАМИКА ОБЪЕМА АЛЬТЕРНАТИВНОГО ОКНА И МОМЕНТ ТАЙМАУТА');
xlabel('Время t, с'); ylabel('Мощность |W_{alt}|'); ylim([-0.5, 6]);
