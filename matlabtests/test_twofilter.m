clear; clc;

% 1. ИНИЦИАЛИЗАЦИЯ ИНВАРИАНТОВ И КОНСТАНТ В СТРУКТУРЕ CFG (UPPERCASE)
cfg.DT                 = 3.0;        % Тактовый интервал дискретизации времени, с
cfg.T_MAX              = 300.0;      % Предельное время наблюдения физического процесса, с
cfg.R_MAX              = 5.0;        % Жесткий физический допуск на линейное перемещение за один такт, км
cfg.R_ALT_MAX          = 6.0;        % Расширенный радиус окрестности для локализации зашумленного плато аномалий, км
cfg.N                  = 20;         % Мощность скользящего множества долговременной стабильности W_main
cfg.S                  = 20;         % Предельная емкость скользящей очереди локальной кучности W_alt
cfg.POOL_SIZE          = 90;         % Физическая емкость монолитного кольцевого хранилища траекторного пула
cfg.T_PROLONGATION_MAX = 15.0;       % Лимит времени адаптивной пролонгации решения при обрыве данных, с
cfg.T_TIMEOUT_CLEAR    = 70.0;       % Критический интервал деградации для очистки альтернативного буфера, с
cfg.S_RETURN           = 6;          % Сокращенный порог мощности W_alt для инициализации возврата к курсу
cfg.MODE_NORM          = int32(10);  % Код режима «Норма» (коррекция по валидным измерениям)
cfg.MODE_BLIND         = int32(20);  % Код режима «Слепое ведение» (автономная экстраполяция по модели)

cfg.X_THRESHOLD_PLATEAU = 20.0;      % Граничный порог для классификации перехода на ложное верхнее плато, км
cfg.BASE_REPER_Y        = 10.0;      % Фиксированная координата репера по оси Y в связанной системе координат, м
cfg.BASE_REPER_Z        = 10.0;      % Фиксированная координата репера по оси Z в связанной системе координат, м
cfg.X_TRUE_REPER        = [10.0; 10.0; 10.0]; % Вектор истинного статического репера курса ТИС для проверки возврата, км
cfg.TIMER_RESET_MARKER  = -100.0;    % Маркер-заглушка для фиксации сброшенного состояния таймера слепой зоны, с

cfg.ZERO_INT           = int32(0);   % Целочисленный ноль для проверки бинарных признаков и индексов
cfg.ZERO_REAL          = 0.0;        % Вещественный ноль для инициализации радиусов и скалярных сумм
cfg.INDEX_SHIFT        = 1;          % Единичный сдвиг для перехода от Си-индексации к индексации MATLAB
cfg.MODE_NORM_MARKER   = 1;          % Числовой маркер для логирования нормального состояния в пуле
cfg.MODE_BLIND_MARKER  = 2;          % Числовой маркер для логирования слепого состояния в пуле
cfg.S_MIN_LIMIT        = 6;          % Нижняя допустимая граница настройки параметра кучности S
cfg.S_MAX_LIMIT        = 20;         % Верхняя допустимая граница настройки параметра кучности S
cfg.STATUS_SUCCESS     = 0;          % Код успешного завершения вычислительного конвейера функции
cfg.STATUS_ERR_CONFIG  = 1;          % Код ошибки инициализации параметров при выходе за допустимые лимиты
cfg.EPSILON_MACHINE    = 2.2204e-16; % Машинный ноль двойной точности для строгого сравнения обусловленности

% 2. СТАТИЧЕСКАЯ АЛЛОКАЦИЯ ВНУТРЕННИХ ВЕКТОРОВ КОНТЕКСТА ПАМЯТИ (CTX)
ctx.GLOBAL_POOL        = zeros(cfg.POOL_SIZE, 5); % Монолитное кольцевое хранилище траекторного пула
ctx.POOL_HEAD          = cfg.ZERO_INT;            % Целочисленный указатель головы кольцевого пула GLOBAL_POOL
ctx.W_MAIN_DATA        = zeros(cfg.N, 1, 'int32'); % Линейный массив скользящего окна долговременной стабильности
ctx.W_MAIN_COUNT       = cfg.ZERO_INT;            % Текущее количество заполненных элементов в окне W_main
ctx.W_MAIN_HEAD        = cfg.ZERO_INT;            % Вспомогательный индекс для совместимости с интерфейсом сдвига
ctx.W_ALT_DATA         = zeros(cfg.S, 1, 'int32'); % Линейный упорядоченный массив скользящей очереди кучности W_alt
ctx.W_ALT_COUNT        = cfg.ZERO_INT;            % Текущее количество накопленных аномальных индексов в очереди W_alt
ctx.W_ALT_HEAD         = cfg.ZERO_INT;            % Вспомогательный индекс для совместимости с операторами очистки

ctx.X_CURRENT          = zeros(3, 1);             % Предвыделенный вектор текущей 3D координаты объекта на такте, км
ctx.X_MAIN_REF         = [10.0; 10.0; 10.0];      % Вектор координат активного опорного математического репера ТИС, км

ctx.T_LAST_DATA_ARRIVAL = 100.0;                  % Временная отметка поступления последнего валидного отсчета датчика, с
ctx.T_BLIND_START       = cfg.TIMER_RESET_MARKER; % Временная отметка инициализации режима автономного прогноза, с
ctx.IS_SWITCHED_TO_25   = false;                  % Логический триггер фиксации перехода системы на ложное плато

ctx.X_FILTERED_OUTPUT   = 10.0;                    % Отфильтрованная координата X на выходе системы для текущего такта, км
ctx.W_ALT_POWER_OUTPUT  = 0.0;                     % Текущая физическая мощность альтернативного окна для логирования, ед

% 3. ВХОДНЫЕ ДАННЫЕ И МОДЕЛИРОВАНИЕ ИЗМЕРИТЕЛЬНОГО ШУМА
t_axes = 0:cfg.DT:cfg.T_MAX;
n_ticks = length(t_axes);

X_true = 10.0 * ones(1, n_ticks);
X_meas = X_true;
X_meas(t_axes == 30.0) = 40.0;
X_meas(t_axes >= 60.0 & t_axes <= 100.0) = 25.0;
X_meas(t_axes >= 171.0 & t_axes <= 216.0) = 25.0;
X_meas(t_axes == 252.0 | t_axes == 255.0) = 28.0;

% Масштабированное зашумление измерительного тракта датчика
noise = 4.0 * rand(size(X_meas)) - 2.0;
X_meas = X_meas + noise;

drop_mask = t_axes > 100.0 & t_axes < 170.0;
X_meas(drop_mask) = NaN;

X_filtered_history = zeros(n_ticks, 1);
W_alt_power_history = zeros(n_ticks, 1);

% 4. ВЫЧИСЛИТЕЛЬНЫЙ ТАКТOВЫЙ КОНВЕЙЕР
for tick = 1:n_ticks
    [status, ctx] = filter2win(cfg, ctx, t_axes(tick), X_meas(tick), drop_mask(tick));
    
    if status ~= cfg.STATUS_SUCCESS
        error('Ошибка конфигурации или крах разрядной сетки ТИС.');
    end
    
    X_filtered_history(tick) = ctx.X_FILTERED_OUTPUT;
    W_alt_power_history(tick) = ctx.W_ALT_POWER_OUTPUT;
end

% 5. АВТОНОМНЫЙ ВЫЗОВ ФУНКЦИИ ОТОБРАЖЕНИЯ ГРАФИКОВ
matplot_twofilter_screen(t_axes, X_true, X_meas, X_filtered_history, W_alt_power_history);
