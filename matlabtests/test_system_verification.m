% =========================================================================
% UNIT ВЕРИФИКАЦИОННЫЙ СТЕНД: АВТОМАТИЧЕСКОЕ ТЕСТИРОВАНИЕ ФУНКЦИЙ ЯДРА
% Responsibility: Модульное тестирование, числовая валидация и контроль точности
% Path: d:\workspace\libtr\matlabtests\test_system_verification.m
% =========================================================================



% Добавляем пути к исследуемому ядру
addpath('d:\workspace\libtr\matlab\');

fprintf('=============================================================\n');
fprintf('СТАРТ АВТОМАТИЧЕСКОГО UNIT-ТЕСТИРОВАНИЯ МАТЕМАТИЧЕСКОГО ЯДРА\n');
fprintf('=============================================================\n\n');

total_tests = 0;
passed_tests = 0;
failed_names = {};

% Инициализируем низкоуровневую библиотеку matlinear
ml = matlinear();

%% -------------------------------------------------------------------------
% ТЕСТ 1: Валидация разложения Холецкого (mat3x3_cholesky)
% -------------------------------------------------------------------------
total_tests = total_tests + 1;
fprintf('Тест 1: Проверка разложения Холецкого матриц 3х3... ');

% Генерируем заведомо симметричную положительно определенную матрицу
A_pos_def = [4, 12, -16; 12, 37, -43; -16, -43, 98];
[status, L] = ml.cholesky(A_pos_def);

% Проверяем математическое условие восстановленной матрицы A = L * L'
if status == 0 && max(max(abs(L * L' - A_pos_def))) < 1e-10
    fprintf('PASSED\n');
    passed_tests = passed_tests + 1;
else
    fprintf('FAILED\n');
    failed_names{end+1} = 'mat3x3_cholesky (Положительно определенная)';
end

%% -------------------------------------------------------------------------
% ТЕСТ 2: Стресс-тест Холецкого на вырожденной матрице
% -------------------------------------------------------------------------
total_tests = total_tests + 1;
fprintf('Тест 2: Защита Холецкого от не знакоопределенных матриц... ');

% Матрица с нулевым собственным значением (ранг 1)
A_degenerate = [1, 2, 3; 2, 4, 6; 3, 6, 9];
[status, ~] = ml.cholesky(A_degenerate);

if status == 1
    fprintf('PASSED (Сбой корректно перехвачен)\n');
    passed_tests = passed_tests + 1;
else
    fprintf('FAILED (Пропущена вырожденная матрица)\n');
    failed_names{end+1} = 'mat3x3_cholesky (Вырожденная защита)';
end

%% -------------------------------------------------------------------------
% ТЕСТ 3: Проверка полного решения СЛАУ (mat3x3_solve_system)
% -------------------------------------------------------------------------
total_tests = total_tests + 1;
fprintf('Тест 3: Точность статического решения систем МНК... ');

AtA = [6, 15, 55; 15, 55, 225; 55, 225, 979];
Atb = [76; 295; 1259];

% Решение встроенными средствами MATLAB (Репер)
x_matlab = AtA \ Atb;

% Решение нашим Си-подобным Холецким-ядром
[status, x_core] = ml.solve_system(AtA, Atb);

if status == 0 && max(abs(x_core - x_matlab)) < 1e-10
    fprintf('PASSED\n');
    passed_tests = passed_tests + 1;
else
    fprintf('FAILED\n');
    failed_names{end+1} = 'mat3x3_solve_system';
end

%% -------------------------------------------------------------------------
% ТЕСТ 4: Проверка обращения матриц МНК (mat3x3_inverse)
% -------------------------------------------------------------------------
total_tests = total_tests + 1;
fprintf('Тест 4: Точность поколоночного инвертирования... ');

A_for_inv = [3, 2, 4; 2, 11, 5; 4, 5, 15];
A_inv_matlab = inv(A_for_inv);

[status, A_inv_core] = ml.inverse(A_for_inv);

if status == 0 && max(max(abs(A_inv_core - A_inv_matlab))) < 1e-10
    fprintf('PASSED\n');
    passed_tests = passed_tests + 1;
else
    fprintf('FAILED\n');
    failed_names{end+1} = 'mat3x3_inverse';
end

%% -------------------------------------------------------------------------
% ТЕСТ 5: Валидация декартово-сферического конвертера (llconverter)
% -------------------------------------------------------------------------
total_tests = total_tests + 1;
fprintf('Тест 5: Проверка инвариантности следа llconverter... ');

P_test = [0, 1000, -1000; 0, 0, 0; 0, 0, 0]; % Станции на оси X
lambda_test = [0; 20000; 0];                 % Цель на удалении 20 км по Y
K_dec_test = diag([25, 100, 4]);              % Декартовы дисперсии: X=25, Y=100, Z=4

% Вызываем конвертер осей
[status, K_sph, std_R, std_Cross, std_Z] = llconverter(P_test, lambda_test, K_dec_test);

% Академическая проверка: при повороте осей след матрицы (trace) обязан сохраняться
trace_error = abs(trace(K_dec_test) - trace(K_sph));

if status == 0 && trace_error < 1e-10
    fprintf('PASSED (Инвариант следа сохранен)\n');
    passed_tests = passed_tests + 1;
else
    fprintf('FAILED (Нарушена геометрия тензорного поворота)\n');
    failed_names{end+1} = 'llconverter';
end

%% -------------------------------------------------------------------------
% ТЕСТ 6: Защита диспетчера от некорректных входных размерностей
% -------------------------------------------------------------------------
total_tests = total_tests + 1;
fprintf('Тест 6: Валидация барьеров защиты диспетчера triangulate... ');

% Передаем пустые массивы, симулируя аппаратный сбой контроллера
[status, ~, ~, ~, ~] = triangulate([], [], [], [], [], 0);

if status > 0
    fprintf('PASSED (Размерностный отказ успешно изолирован)\n');
    passed_tests = passed_tests + 1;
else
    fprintf('FAILED (Пропущен критический сбой памяти)\n');
    failed_names{end+1} = 'triangulate (Аппаратная защита)';
end

%% =========================================================================
% ИТОГОВЫЙ ОТЧЕТ СТЕНДА СХОДИМОСТИ КЛИЕНТСКИХ ФУНКЦИЙ
% =========================================================================
fprintf('\n-------------------------------------------------------------\n');
fprintf('ОТЧЕТ ЮНИТ-ТЕСТИРОВАНИЯ: ПРОВЕДЕНО ТЕСТОВ: %d | УСПЕШНО: %d | СБОИ: %d\n', ...
    total_tests, passed_tests, total_tests - passed_tests);
fprintf('-------------------------------------------------------------\n');

if passed_tests == total_tests
    fprintf('СТАТУС СИСТЕМЫ: МАТЕМАТИЧЕСКОЕ ЯДРО ПОЛНОСТЬЮ ВЕРИФИЦИРОВАНО И ГОТОВО К ПЕРЕНОСУ\n');
else
    fprintf('КРИТИЧЕСКИЙ СТАТУС: ОБНАРУЖЕНЫ СБОИ В СЛЕДУЮЩИХ МОДУЛЯХ:\n');
    for idx = 1:length(failed_names)
        fprintf('  - %s\n', failed_names{idx});
    end
end
fprintf('=============================================================\n');
